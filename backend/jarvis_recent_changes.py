"""jarvis_recent_changes.py - "what changed in your last update?",
answered from the project's own record.

GENERATED by tools/gen_recent_changes.py from CHANGELOG.md and the newest
changelog.d fragments. DO NOT HAND-EDIT. The live backend folder carries
neither of those files, so the newest user-visible bullets travel as data,
exactly like jarvis_feature_catalogue.py carries the feature list.

The VERSION is NOT baked in: it is read beside this module at answer time,
so a build number can never disagree with the text.

Regenerate with:  py -3 tools/gen_recent_changes.py
Check it is current:  py -3 tools/gen_recent_changes.py --check
"""
from __future__ import annotations

from pathlib import Path

#: The newest user-visible changes on record, newest first. Each is the
#: record's own bold title, with its trailing date removed.
BULLETS = (
    'The undo notice after an approved card times out after 15 seconds',
    'The deploy tool now sees a patch that was EXTENDED in place, and upgrades the live github-tools block instead of reporting it already present',
    'A photo can be sent from your phone into "From my phone", exactly as a document is',
    "The patch history is rebuilt after the union's patch edits, so the required `backend` and `backend-windows` jobs pass again",
    'A free-plan 403 on branch rules means "no rules", not "blind token" - so the owner-approved merge in the field-test repository can land',
)


#: One fixed sentence for a record that carries nothing - never an
#: invented list and never the model's guess.
NO_RECORD_WORDS = (
    "The newest changes are not written down beside the program on this PC, "
    "so I will not guess.")


def version() -> str:
    """The VERSION beside this module, or "" when this PC has none."""
    try:
        text = (Path(__file__).resolve().parent / "VERSION").read_text(
            encoding="utf-8", errors="replace").strip()
    except OSError:
        return ""
    return text if text else ""


def bullets(limit: int = 3) -> list:
    """The newest bullets, at most `limit`, never a guess."""
    try:
        n = int(limit)
    except (TypeError, ValueError):
        n = 3
    return [b for b in BULLETS if b][: max(0, n)]


def answer(limit: int = 3) -> str:
    """What changed in the last update: the version, then the real bullets."""
    got = version()
    lead = (f"This PC runs Jarvis {got}." if got
            else "The version is not written down beside the program on this PC.")
    items = bullets(limit)
    if not items:
        return lead + " " + NO_RECORD_WORDS
    listed = "; ".join(item.rstrip(".;") for item in items)
    return lead + " The newest changes on record are: " + listed + "."
