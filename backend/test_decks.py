        check("one new card a day: the day's new card is used up", w.d.list_decks()["ready"] == 0)
        w.clock.t = S.wall_to_epoch(2026, 10, 2, 23, 59)
        check("still the same local day at 23:59", w.d.list_decks()["ready"] == 0)
        w.clock.t = S.wall_to_epoch(2026, 10, 3, 0, 1)
        ls = w.d.list_decks()
        check("just after local midnight it is a new day: the new-card allowance is back", ls["new_left"] == 1
              and ls["ready"] >= 1, json.dumps(ls))
        os.environ["TZ"] = "America/Los_Angeles"
        time.tzset()
        t = S.wall_to_epoch(2026, 10, 2, 23, 0)
        w2 = World(t=t)
        v2 = w2.d.create_deck("West")
        w2.d.set_new_per_day(1)
        w2.d.keep({"deck": v2["id"]}, mkcards(2))
        study(w2.d, w2.d.review_state()["card"]["id"], "easy")
