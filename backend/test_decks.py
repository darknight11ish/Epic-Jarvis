def t_delete_leaves_no_trace():
    w = World()
    v = w.d.create_deck("Gone soon")
    w.d.keep({"deck": v["id"]}, mkcards(3))
    con = sqlite3.connect(str(w.path))
    blobs = [r[0] for r in con.execute("select front from cards")] + \
            [r[0] for r in con.execute("select passage from cards")] + \
            [r[0] for r in con.execute("select name from decks")]
    con.close()
    raw = w.path.read_bytes()
    check("before: the sealed pieces are in the file", all(b in raw for b in blobs))
    cid = w.d.deck_cards(v["id"])["cards"][0]["id"]
    one = sqlite3.connect(str(w.path)).execute("select front, back, passage from cards where id=?", (cid,)).fetchone()
    w.d.card_act(v["id"], cid, "delete")
    raw = w.path.read_bytes()
    check("a deleted card's sealed front, back and passage are gone from the file",
          not [b for b in one if bytes(b) in raw])
    w.d.deck_act(v["id"], "delete")
    raw = w.path.read_bytes()
    check("a deleted deck leaves none of its sealed bytes", not [b for b in blobs if bytes(b) in raw])
    check("the deck list is empty again", w.d.list_decks()["decks"] == [])


