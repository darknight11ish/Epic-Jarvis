class Clock:
    def __init__(self, t):
        self.t = float(t)

    def __call__(self):
        return self.t


T0 = S.wall_to_epoch(2026, 10, 1, 9, 0)


class KeyUnavailable(Exception):
    """Same name as jarvis_chat_log's, whose message is plain words."""


class World:
    def __init__(self, t=T0, key=KEY, **kw):
        self.clock = Clock(t)
        self.events, self.cards = [], []
        n = len(os.listdir(_TMP))
        self.sched = S.Scheduler(_TMP / f"sched-{n}.db", clock=self.clock, spawn=lambda fn: fn(),
                                 publish=lambda k, d: self.events.append((k, dict(d))),
                                 gate=lambda *a, **k2: self.cards.append(a) or ("approved", ""))
        S._SCHED = self.sched
        self.path = _TMP / f"study-{n}.db"
        self.d = D.Decks(self.path, (lambda: key) if not callable(key) else key,
                         clock=self.clock, scheduler=self.sched, fuzz=False, **kw)
        D._ONE = self.d


def mkcards(k, prefix="Q", start=0):
    return [{"n": i + 1, "front": f"{prefix}{i} question?", "back": f"{prefix}{i} answer",
             "passage": f"{prefix}{i} passage words", "kind": "recall", "level": "",
             "key_source": ""} for i in range(start, start + k)]


def study(d, cid, rating="good"):
    d.reveal(cid)
    return d.rate(cid, rating)


def raises(fn, code):
    try:
        fn()
    except D.DeckError as e:
        return e.code == code and e.message.endswith((".", "?")) or e.code == code
    except Exception:
        return False
    return False


