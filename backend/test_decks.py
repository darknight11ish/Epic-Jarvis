def t_the_scheduler_kind():
    k = S.KINDS.get("review")
    check("`review` is a registered kind: plain_repeat, silent, single, not notify, listed",
          k is not None and k.plain_repeat and k.silent and k.single and not k.notify
          and k.owner_listed and not k.has_text)
    check("jarvis_schedule loads this module before its loop (KIND_MODULES)", "jarvis_decks" in S.KIND_MODULES)
    w = World()
    check("no deck, no job, no line", w.sched.jobs_of("review") == [] and w.d.line() == ""
          and w.sched.listed() == [])
    a = w.d.create_deck("First")
    jobs = w.sched.jobs_of("review")
    check("the first deck makes exactly one job", len(jobs) == 1, jobs)
    j = w.sched.job(jobs[0])
    check("... active at once, no approval card raised", j["state"] == "active" and w.cards == [])
    check("... going off rings nothing (notify false) and it has no words of its own",
          j.get("notify") is False and j["text"] == "" and j["kind"] == "review", json.dumps(j))
    check("... once a day at 04:00", j["repeat"].endswith("04:00"), j["repeat"])
    w.d.create_deck("Second")
    check("a second deck keeps the one job", w.sched.jobs_of("review") == jobs)
    w.d.keep({"deck": a["id"]}, mkcards(3))
    listed = [x for x in w.sched.listed() if x["kind"] == "review"]
    check("Coming up shows it once, with the 'N cards ready' note",
          len(listed) == 1 and listed[0].get("note") == "3 cards ready", json.dumps(listed))
    w.d.deck_act(a["id"], "pause")
    check("pausing every deck with cards reads 'All decks paused'... only when all are paused",
          w.d.line() == "Nothing ready today")
    b = [x for x in w.d.list_decks()["decks"] if x["name"] == "Second"][0]
    w.d.deck_act(b["id"], "pause")
    check("all decks paused says so", w.d.line() == "All decks paused")
    w.d.deck_act(a["id"], "resume")
    w.d.deck_act(b["id"], "resume")
    w.sched.act(jobs[0], "delete")
    check("the job removed by hand is put back by the next look", w.d.ensure_job() == "added"
          and len(w.sched.jobs_of("review")) == 1)
    w.d.deck_act(a["id"], "delete")
    check("deleting one of two decks keeps the job", len(w.sched.jobs_of("review")) == 1)
    w.d.deck_act(b["id"], "delete")
    check("deleting the last deck removes the job", w.sched.jobs_of("review") == [] and w.d.line() == "")
    check("no approval card was raised at any point", w.cards == [])
    ev = json.dumps(w.events)
    check("no event carried a deck's words", "First" not in ev and "Second" not in ev)
    after = w.sched.add_repeat("review", dict(D.JOB_RULE), source="decks")
    try:
        w.sched.add_repeat("review", dict(D.JOB_RULE), source="decks")
        second = True
    except Exception:
        second = False
    check("the scheduler itself refuses a second review job (single)", after and not second)


