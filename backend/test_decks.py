def t_sealed_bytes():
    w = World()
    v = w.d.create_deck("Diabetes notes")
    cards = [{"n": 1, "front": "What does insulin regulate?", "back": "Blood glucose levels",
              "passage": "Insulin lowers blood glucose after meals.", "kind": "recall",
              "level": "", "key_source": ""},
             {"n": 2, "front": "Cuesta ___ mucho", "back": "Nunca", "passage": "Ella se cuesta ahorrar dinero.",
              "kind": "blank", "level": "B1", "key_source": "text"}]
    w.d.keep({"deck": v["id"]}, cards)
    raw = w.path.read_bytes()
    words = ["Diabetes", "insulin", "Insulin", "glucose", "Blood", "Cuesta", "Nunca", "ahorrar",
             "dinero", "notes", "question"]
    check("no deck name, question, answer or passage is in the file's bytes",
          not [x for x in words if x.encode() in raw], [x for x in words if x.encode() in raw])
    check("the plain columns (kind, level tag) are there, as designed",
          b"recall" in raw and b"B1" in raw)
    con = sqlite3.connect(str(w.path))
    row = con.execute("select name from decks").fetchone()
    blobs = [r[0] for r in con.execute("select front from cards")]
    con.close()
    check("the sealed name is bytes, nonce first (12) then tag-carrying ciphertext",
          isinstance(row[0], bytes) and len(row[0]) >= 12 + 16 + len("Diabetes notes"))
    check("two cards' fronts are different bytes (fresh nonces)", blobs[0] != blobs[1])
    fresh = D.Decks(w.path, lambda: KEY, clock=w.clock, fuzz=False)
    got = fresh.deck_cards(v["id"])
    check("a fresh object with the same key reads everything back",
          [c["front"] for c in got["cards"]] == ["What does insulin regulate?", "Cuesta ___ mucho"]
          and got["deck"]["name"] == "Diabetes notes" and got["cards"][1]["level"] == "B1")
    wrong = D.Decks(w.path, lambda: b"z" * 32, clock=w.clock, fuzz=False)
    check("a different key does not open it",
          raises(lambda: wrong.deck_cards(v["id"]), "deck_unavailable"))
    swapped = sqlite3.connect(str(w.path))
    a = swapped.execute("select id, front from cards order by rowid").fetchall()
    swapped.execute("update cards set front=? where id=?", (a[1][1], a[0][0]))
    swapped.commit()
    swapped.close()
    check("a sealed piece moved to another card does not open (the row's address is authenticated)",
          raises(lambda: D.Decks(w.path, lambda: KEY, clock=w.clock).deck_cards(v["id"]), "deck_unavailable"))


