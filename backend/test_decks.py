def t_pin_and_golden():
    check("py-fsrs is exactly 6.3.2", metadata.version("fsrs") == "6.3.2", metadata.version("fsrs"))
    reqs = (HERE / "requirements.txt").read_text(encoding="utf-8")
    lines = [l for l in reqs.split("\n") if l.strip() and not l.lstrip().startswith("#")]
    fs = [l for l in lines if l.startswith("fsrs")]
    check("requirements.txt pins fsrs==6.3.2 exactly", len(fs) == 1 and fs[0].split("#")[0].strip() == "fsrs==6.3.2", fs)
    check("... without the optimizer extra, and no torch requirement at all",
          "[" not in fs[0].split("#")[0] and not [l for l in lines if re.match(r"torch\b", l)])
    lock = (HERE / "requirements.lock").read_text(encoding="utf-8")
    check("the hash-locked list holds fsrs 6.3.2 and no torch",
          "fsrs==6.3.2 \\" in lock and not re.search(r"^torch==", lock, re.M))
    g = json.loads((HERE / "decks_fsrs_golden.json").read_text(encoding="utf-8"))
    check("the golden file was made from 6.3.2", g["fsrs"] == "6.3.2" and len(g["sequences"]) >= 6)
    for name, rows in g["sequences"].items():
        st = D.new_state(g["start"])
        good = True
        detail = ""
        for row in rows:
            st = D.review(st, row["rating"], row["at"], fuzz=False)
            for k, v in row["after"].items():
                a = st[k]
                same = (a is None and v is None) or (a is not None and v is not None
                                                     and abs(float(a) - float(v)) <= 1e-9 * max(1.0, abs(float(v))))
                if not same:
                    good = False
                    detail = f"{name} {row['rating']} {k}: {a!r} != {v!r}"
        check(f"the wrapper reproduces py-fsrs's numbers: {name}", good, detail)


def t_scheduler_properties():
    ivs = {}
    for r in D.RATINGS:
        st = D.review(D.new_state(T0), r, T0, fuzz=False)
        ivs[r] = st["due"] - T0
        check(f"a first {r}: the due date is after the review", st["due"] > T0)
    check("first ratings: Easy >= Good >= Hard >= Again",
          ivs["easy"] >= ivs["good"] >= ivs["hard"] >= ivs["again"], ivs)
    check("Again on a new card comes back in a day (no same-day learning steps)", ivs["again"] == DAY)
    mature = D.new_state(T0)
    at = T0
    for _ in range(3):
        mature = D.review(mature, "good", at, fuzz=False)
        at = mature["due"]
    after = {r: D.review(mature, r, at, fuzz=False)["due"] - at for r in D.RATINGS}
    check("a settled card: Easy >= Good >= Hard >= Again, and Again is the shortest",
          after["easy"] >= after["good"] >= after["hard"] >= after["again"]
          and after["again"] < after["good"], after)
    check("Again on a settled card never asks for less than a day, and stays a review card",
          after["again"] >= DAY and D.review(mature, "again", at, fuzz=False)["state"] == 2)
    check("a rating that is not one of the four is refused",
          raises(lambda: D.review(D.new_state(T0), "meh", T0), "bad_rating"))
    fz = [D.review(mature, "good", at, fuzz=True)["due"] - at for _ in range(30)]
    check("fuzzing (real use) spreads long intervals a little and never below a day",
          len(set(fz)) > 1 and min(fz) >= DAY)


