"""test_tool_updates.py - "Check for tool updates" (jarvis_tool_updates.py,
tool-updates.patch; the owner's own request, made directly).

    python3 backend/test_tool_updates.py

Runs anywhere; no model, and NO REAL NETWORK CALL - every PyPI, crates.io
and GitHub fetch is a fake function this file supplies. What it proves:

1. Parsing: requirements.lock's `name==version` lines (continuations joined,
   duplicate-marker lines deduped) and Cargo.lock's `[[package]]` entries
   (a local, sourceless package such as jarvis-desktop itself is skipped;
   only a crates.io registry source counts).
2. The report: an outdated package/crate is flagged with the exact command
   to run (never executed here or anywhere in the module - the module
   imports no subprocess, no os.system); an up-to-date one is not; a fetch
   that fails lands in "unreachable", never raises; the summary sentence
   counts correctly. crates.io is asked once per crate NAME, not once per
   pinned version.
3. A missing requirements.lock/rust-crates.lock says so plainly (available:
   false, why), rather than reporting zero tools.
4. GitHub tools: empty by default (and says why, in GITHUB_TOOLS_NOTE); a
   fake pinned tool with a fake 403 answer becomes one WARN line
   ("unreachable"), never a crash - the rate-limit case the brief asks for.
5. The one-time card: not yet approved needs a person's yes (denied/timed
   out add nothing; approved sets the flag AND runs the check in the same
   thread); already approved runs straight away, no gate call at all;
   a non-"ask" tier is refused (503).
6. Never says "vulnerable" (that is check_python_advisories.py's job, not
   this one) and never imports anything that could execute a shell command.
7. The route and the patch: install() answers /api/tool_updates and
   /api/tool_updates/check after the server's own checks and passes
   everything else on; tool-updates.patch applies after the rest of the
   stack and reverses; the module is shipped.
"""
