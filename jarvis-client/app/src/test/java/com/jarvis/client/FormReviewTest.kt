package com.jarvis.client

import com.jarvis.client.data.SecurityRules
import com.jarvis.client.net.FormReview
import com.jarvis.client.net.JarvisJson
import com.jarvis.client.net.decodePendingRows
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.util.Base64

/**
 * The picture of a filled-in web form on the "submit this form" card
 * (`net/FormReview.kt`, docs/FORM-REVIEW-DESIGN.md). Pure JVM.
 *
 * The rows here are written by hand for this test: the shared fixtures are
 * generated by the backend and carry no picture row.
 */
class FormReviewTest {

    private fun json(text: String): JsonElement = JarvisJson.parseToJsonElement(text)
    private fun obj(text: String): JsonObject = json(text) as JsonObject

    private fun row(detail: String?): JsonElement {
        val d = if (detail == null) "" else ""","detail":$detail"""
        return json("""{"id":"c1","action":"browser_form_submit","tier":"ask"$d}""")
    }

    // ---- the id in the row's detail ----

    @Test
    fun `picture id is read from a detail object`() {
        assertEquals("ab12-CD_34", FormReview.pictureIdOf(obj("""{"picture":"ab12-CD_34","site":"x.com"}""")))
    }

    @Test
    fun `picture id is read from a detail that is JSON text`() {
        val text = JsonPrimitive("""{"picture":"p77","site":"x.com"}""")
        assertEquals("p77", FormReview.pictureIdOf(text))
    }

    @Test
    fun `no picture means null`() {
        assertNull(FormReview.pictureIdOf(null))
        assertNull(FormReview.pictureIdOf(obj("""{"site":"x.com"}""")))
        assertNull(FormReview.pictureIdOf(JsonPrimitive("just some words")))
        assertNull(FormReview.pictureIdOf(JsonPrimitive("""["picture"]""")))
        assertNull(FormReview.pictureIdOf(obj("""{"picture":""}""")))
        assertNull(FormReview.pictureIdOf(obj("""{"picture":"   "}""")))
        assertNull(FormReview.pictureIdOf(obj("""{"picture":{"id":"x"}}""")))
        assertNull(FormReview.pictureIdOf(obj("""{"picture":null}""")))
    }

    @Test
    fun `an unusable id is refused, not sent`() {
        assertNull(FormReview.pictureIdOf(obj("""{"picture":"a b"}""")))
        assertNull(FormReview.pictureIdOf(obj("""{"picture":"${"x".repeat(200)}"}""")))
        assertNull(FormReview.pathFor(""))
        assertNull(FormReview.pathFor("has space"))
    }

    // ---- the row as the phone reads it ----

    @Test
    fun `a row with a picture id in an object detail carries it`() {
        val read = decodePendingRows(listOf(row("""{"picture":"pic1","site":"x.com"}""")), 0L)
        assertEquals(0, read.skipped)
        assertEquals("pic1", read.items.single().formPicture)
    }

    @Test
    fun `a row with a picture id in a text detail carries it`() {
        val text = "\"{\\\"picture\\\":\\\"pic2\\\",\\\"site\\\":\\\"x.com\\\"}\""
        val read = decodePendingRows(listOf(row(text)), 0L)
        assertEquals("pic2", read.items.single().formPicture)
    }

    @Test
    fun `a row without a picture is unchanged`() {
        val plain = decodePendingRows(listOf(row("""{"site":"x.com"}""")), 0L).items.single()
        assertNull(plain.formPicture)
        val none = decodePendingRows(listOf(row(null)), 0L).items.single()
        assertNull(none.formPicture)
    }

    @Test
    fun `a row cannot bring its own form_picture key`() {
        val sneaky = json("""{"id":"c2","action":"browser_form_submit","form_picture":"sneaky"}""")
        assertNull(decodePendingRows(listOf(sneaky), 0L).items.single().formPicture)
    }

    // ---- the request ----

    @Test
    fun `the path carries the id URL-encoded`() {
        assertEquals("/api/form-review/picture?id=abc123", FormReview.pathFor("abc123"))
        assertEquals("/api/form-review/picture?id=a%26b%3Dc%2Fd", FormReview.pathFor("a&b=c/d"))
        assertEquals("/api/form-review/picture?id=a-b_c.d", FormReview.pathFor("a-b_c.d"))
    }

    // ---- the answer ----

    @Test
    fun `a good answer is a picture`() {
        val a = FormReview.answer(200, obj("""{"ok":true,"jpeg":"AAAA","width":800,"height":600}"""))
        assertEquals(FormReview.Answer.Picture("AAAA", 800, 600), a)
    }

    @Test
    fun `a 404 is gone, not a crash`() {
        assertEquals(FormReview.Answer.Gone, FormReview.answer(404, obj("""{"ok":false}""")))
        assertEquals(FormReview.Answer.Gone, FormReview.answer(404, null))
    }

    @Test
    fun `anything else is the could-not-load sentence`() {
        val words = FormReview.COULD_NOT_LOAD
        assertEquals(FormReview.Answer.Failed(words), FormReview.answer(500, null))
        assertEquals(FormReview.Answer.Failed(words), FormReview.answer(200, null))
        assertEquals(FormReview.Answer.Failed(words), FormReview.answer(200, obj("""{"ok":true}""")))
        assertEquals(FormReview.Answer.Failed(words), FormReview.answer(200, obj("""{"ok":false,"jpeg":"AAAA"}""")))
        assertEquals(FormReview.Answer.Failed(words), FormReview.answer(200, obj("""{"ok":true,"jpeg":7}""")))
    }

    @Test
    fun `the could-not-load words are the agreed sentence`() {
        assertEquals(
            "Jarvis could not load the picture of the form. Read the details below before you approve.",
            FormReview.COULD_NOT_LOAD,
        )
        assertEquals("The form as Jarvis filled it in", FormReview.PICTURE_DESCRIPTION)
    }

    // ---- decoding ----

    @Test
    fun `base64 decodes, and garbage fails safely`() {
        val bytes = byteArrayOf(1, 2, 3, 4, 5, 6, 7)
        val text = Base64.getEncoder().encodeToString(bytes)
        assertTrue(bytes.contentEquals(FormReview.decodeBytes(text)))
        assertNull(FormReview.decodeBytes("!!! not base64 !!!"))
        assertNull(FormReview.decodeBytes("a"))
        assertNull(FormReview.decodeBytes(""))
    }

    // ---- screenshots ----

    @Test
    fun `screenshots are blocked while a form picture shows`() {
        val off = com.jarvis.client.data.Security(appLock = false, privateLists = false)
        assertFalse(SecurityRules.blockScreenCapture(off))
        assertTrue(SecurityRules.blockScreenCapture(off, formPictureShown = true))
    }

    @Test
    fun `the shown count goes up and down and never below zero`() {
        val start = FormReview.shown.value
        FormReview.enterView()
        assertEquals(start + 1, FormReview.shown.value)
        FormReview.leaveView()
        assertEquals(start, FormReview.shown.value)
        repeat(start + 2) { FormReview.leaveView() }
        assertEquals(0, FormReview.shown.value)
    }
}
