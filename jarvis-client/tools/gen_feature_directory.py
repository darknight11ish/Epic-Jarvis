#!/usr/bin/env python3
"""Generate jarvis-client's FeatureDirectory.kt from the repository contract.

    python3 jarvis-client/tools/gen_feature_directory.py          # write
    python3 jarvis-client/tools/gen_feature_directory.py --check  # compare

SOURCE OF TRUTH: contract/feature-controls.json (generated by lock-hook's
feature-controls work; five approved labels). This script writes the Android
artifact the phone consumes, so the rows are NEVER hand-typed and cannot drift
from the contract. The counts are the contract's own `feature_count` and the
length of its row list, never a literal, so a new feature row is a
regeneration, not an edit here. It is the phone-side generator: the shared
contract generator produces the JSON, this one turns it into Kotlin.

The artifact is data only: labels, words, example phrase, screen path, and (for
rows the contract labels Switchable/Adjustable) the setting keys. The screen
decides nothing itself; `FeatureDirectoryTest` pins count/labels/example/path
rules, including that no other label may name a setting.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
CONTRACT = ROOT / "contract" / "feature-controls.json"
OUT = (ROOT / "jarvis-client" / "app" / "src" / "main" / "java" / "com"
       / "jarvis" / "client" / "net" / "FeatureDirectory.kt")

#: The five labels, in the contract's order, must be exactly these.
LABELS = (
    "Switchable / Adjustable (Typed & Settings)",
    "Settings-Only (By Design \u2014 Security Boundary)",
    "PC-Only Setting (Honest Refusal on Phone)",
    "Command-Only (Runs When You Ask \u2014 No Switch Needed)",
    "Always On (Core Safety Rule \u2014 Cannot Be Turned Off)",
)


def kt(s) -> str:
    text = "" if s is None else str(s)
    return '"' + (text.replace("\\", "\\\\").replace('"', '\\"')
                  .replace("$", "\\$").replace("\n", "\\n")) + '"'


#: Words that already say the sentence is about the PC: "on the PC",
#: "on your PC", or the "PC: ..." prefix. A row carrying one of these is left
#: exactly as the contract wrote it.
_PC_ALREADY_SAID = re.compile(r"(?i)\bon (?:the|your) pc\b|\bpc:")


def phone_why(f: dict) -> str:
    """The row's words as the PHONE may show them.

    A `desktop`-surface row's `where` is the PC's own place - "Settings,
    Accounts - the private calendar link", "Brain, Memory, What Jarvis knows
    about you", "Settings, Shortcuts" - and this artifact is drawn on the
    phone, which has no Accounts section, no tray icon and no Brain rail tabs.
    Read on the phone with no qualifier, those words dead-end: the settings
    wrong-app audit of 2026-10-29 (findings 1 and 2) counted 17 such rows.
    So the PC is named in front, once, unless the contract's sentence already
    names it. The contract is never modified here; the page's own copy of the
    same words (jarvis-desktop/src/feature-directory.js) keeps them as written,
    where they ARE this app's place.
    """
    why = str(f.get("where") or "")
    if str(f.get("surface") or "") == "desktop" and not _PC_ALREADY_SAID.search(why):
        return "On your PC: " + why
    return why


def row(f: dict) -> dict:
    control = f.get("control") or {}
    evidence = f.get("label_evidence") or {}
    label = str(f.get("label") or "")
    # The directory is a PHONE surface and draws no toggle. `setting_keys` is
    # the contract's record of the switch keys a row's control names; this app
    # may only name one on a Switchable/Adjustable row, because every other
    # label says the phone has no control for the feature (PC-Only included).
    # A PC-Only row can still be a real switch on the PC - the contract records
    # that, and the desktop page never renders keys at all - but listing it here
    # would offer a control this app does not have, which is the fake-switch
    # rule FeatureDirectoryTest holds. So the keys are dropped for every other
    # label, never rendered.
    keys = [str(k) for k in (control.get("setting_keys") or [])]
    if label != LABELS[0]:
        keys = []
    adjusts = [str(a) for a in (control.get("adjust") or [])]
    command = f.get("command") or {}
    return {
        "id": str(f.get("id") or ""),
        "name": str(f.get("name") or ""),
        "group": str(f.get("group") or ""),
        "surface": str(f.get("surface") or ""),
        "label": label,
        "why": phone_why(f),
        "examplePhrase": str(evidence.get("example_phrase") or ""),
        "exampleWords": str(evidence.get("example_phrase") or ""),
        "settingsPath": str(evidence.get("screen_path") or ""),
        "typedControls": adjusts,
        "switchKeys": keys,
        "planned": str(f.get("status") or "") == "planned",
        "plannedWords": (str(f.get("reason") or "")
                         if str(f.get("status") or "") == "planned" else ""),
        "settingsGap": "" if command.get("settings_gap") in (None, "None", "") else str(command.get("settings_gap")),
        "reasonCode": str(command.get("reason_code") or f.get("status") or ""),
        # A real switch is a row the contract labels Switchable AND which names
        # its setting key; every other row must offer nothing (tested).
        "isToggle": label == LABELS[0] and bool(keys),
    }


def render(contract: dict) -> str:
    features = contract.get("features") or []
    rows = [row(f) for f in features]
    bad = [r["label"] for r in rows if r["label"] not in LABELS]
    if bad:
        raise SystemExit(f"contract carries a label not in the five: {sorted(set(bad))}")
    lines = [
        "package com.jarvis.client.net",
        "",
        "// GENERATED by jarvis-client/tools/gen_feature_directory.py from",
        f"// contract/feature-controls.json ({contract.get('feature_count')} features)",
        "// - do not edit by hand. Run the generator and commit its output.",
        "",
        "/**",
        f" * The {len(rows)} features and abilities, in the PC's own five labels,",
        " * words, example phrases and screen paths (contract/feature-controls.json).",
        " * Searchable in Settings and drawn with no fake toggles: only a row the",
        " * contract says is a real switch offers one.",
        " */",
        "object FeatureDirectory {",
        "    const val VERSION = 1",
        f"    const val COUNT = {len(rows)}",
        "",
        "    data class Row(",
        "        val id: String,",
        "        val name: String,",
        "        val group: String,",
        "        val surface: String,",
        "        val label: String,",
        "        val why: String,",
        "        val examplePhrase: String,",
        "        val exampleWords: String,",
        "        val settingsPath: String,",
        "        val typedControls: List<String>,",
        "        val switchKeys: List<String>,",
        "        val planned: Boolean,",
        "        val plannedWords: String,",
        "        val settingsGap: String,",
        "        val reasonCode: String,",
        "        val isToggle: Boolean,",
        "    )",
        "",
        "    val ROWS: List<Row> = listOf(",
    ]
    for r in rows:
        lines.append(
            "        Row(" + ", ".join([
                kt(r["id"]), kt(r["name"]), kt(r["group"]), kt(r["surface"]),
                kt(r["label"]), kt(r["why"]), kt(r["examplePhrase"]),
                kt(r["exampleWords"]), kt(r["settingsPath"]),
                "listOf(" + ", ".join(kt(x) for x in r["typedControls"]) + ")",
                "listOf(" + ", ".join(kt(x) for x in r["switchKeys"]) + ")",
                "true" if r["planned"] else "false",
                kt(r["plannedWords"]), kt(r["settingsGap"]),
                kt(r["reasonCode"]), "true" if r["isToggle"] else "false",
            ]) + "),")
    lines += [
        "    )",
        "",
        "    /** The five approved label strings, exactly as the contract sends them. */",
        "    val LABELS: List<String> = ROWS.map { it.label }.distinct()",
        "",
        "    private val BY_ID: Map<String, Row> = ROWS.associateBy { it.id }",
        "",
        "    fun row(id: String): Row? = BY_ID[id]",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    want = render(contract)
    have = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
    if args.check:
        if want != have:
            print(f"STALE {OUT.relative_to(ROOT)} - run this generator")
            return 1
        print(f"ok  {OUT.relative_to(ROOT)} matches contract/feature-controls.json")
        return 0
    OUT.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(want.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
