fn main() {
    // Declaring an app manifest is what turns the ACL on for this app's OWN
    // commands. Without it `has_app_manifest()` is false and Tauri's permission
    // check short-circuits: every `#[tauri::command]` is callable from every
    // window regardless of what the capability files say. The capability file
    // used to describe itself as a "least-privilege IPC surface" while gating
    // nothing app-defined, which is worse than having no file at all.
    //
    // `commands` autogenerates an `allow-<kebab-name>` and `deny-<kebab-name>`
    // permission per entry into `permissions/autogenerated/`. The sets in
    // `permissions/` group those per surface, and `capabilities/*.json` hands
    // each window only its own set.
    //
    // Anything added to `generate_handler!` in lib.rs must be added here too,
    // or it is reachable from nowhere and the failure is a runtime "not allowed
    // on window" rather than a compile error.
    let attributes =
        tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(&[
            // Chat
            "stream_chat",
            "cancel_chat",
            "set_route_lane",
            // The fanned-out event stream
            "get_link_state",
            "get_pending_approvals",
            "refresh_link",
            "decide_approval",
            // A note on a proposal, and the controls for the turn already
            // running. `jarvis-link.js` invoked all five of these before any
            // of them existed, so every one of those buttons failed at the
            // Tauri boundary - see permissions/surfaces.toml's "approvals"
            // and "task-control" sets for which windows get them.
            "amend_approval",
            "pause_task",
            "resume_task",
            "stop_task",
            "inject_task_note",
            // The interruption budget and the daily brief. Reads and two
            // writes; the tray calls the same functions in-process, so it
            // needs no grant.
            "get_digest",
            "mark_digest_seen",
            "set_attention_muted",
            // The Brain. One fan-out read over a fixed allowlist, then one
            // command per power it can exercise.
            "brain_read",
            "brain_revert_undo",
            "brain_cancel_job",
            "brain_cancel_hold",
            "brain_watch_add",
            "brain_watch_remove",
            "brain_watch_seen",
            "brain_remove_skill",
            "brain_model",
            // Memory: one decision per fact, and the switch that governs
            // whether facts are proposed at all.
            "brain_memory_decide",
            "brain_memory_forget",
            "brain_memory_edit",
            "brain_memory_learning",
            "brain_memory_export",
            "brain_memory_as_of",
            // Same omission as `restart_app` below: in generate_handler! and
            // called by brain.js, absent here, so unreachable from every
            // window.
            "brain_memory_sleep_time",
            // "Both are true" on a correction card (memory-intake.patch).
            "brain_memory_keep_both",
            // Backend supervision — settings window only
            "supervisor_status",
            "set_supervision",
            "start_backend",
            "stop_backend",
            // The theme. Readable everywhere, writable from the two windows
            // that offer a picker.
            "get_theme",
            "set_theme",
            // "Match Windows light or dark mode": the read is everywhere the
            // theme is, the switch is with the two pickers.
            "get_theme_prefs",
            "set_theme_follow_system",
            // Settings' "Open Faces" button.
            "open_faces",
            // The right/wrong mark on one answer (feedback.patch). Quickbar.
            "mark_answer",
            // The first-run walkthrough — one command, closes itself.
            "finish_onboarding",
            // Connection settings — settings window only
            "get_api_settings",
            "set_api_settings",
            // Settings' "Show the token for my phone". Settings window only.
            "reveal_pairing_token",
            // Settings' "Second graphics card": read what was found and the
            // switches, and turn ONE switch on or off. ON only raises an
            // approval card. Settings window only.
            "get_second_card",
            "set_second_card",
            // Settings' "Big model (slow)" (backend/big-model.patch): read
            // what was found and the three switches, and turn ONE switch on
            // or off. ON only raises an approval card. Settings window only.
            "get_big_model",
            "set_big_model",
            // Settings' "Voice": what the PC's voice settings are (GET
            // /api/voice/status) - whether each microphone's voice print is
            // trained, the wake word, the stop word, Smart Turn. Read only.
            // Settings window only.
            "get_voice_status",
            // Settings' "Voice": the PC's "hey Jarvis" switch. OFF at once
            // (and this PC stops listening); ON only raises an approval card,
            // and is held while the event stream is stale. Settings only.
            "set_wake_word",
            // Widget geometry and capture
            "get_appearance",
            "set_appearance",
            // The in-memory appearance, for windows that only draw it: no
            // network call and no broadcast, so safe inside a listener.
            "appearance_snapshot",
            "appearance_colours",
            "update_status",
            "check_for_update",
            "set_update_check_on_start",
            "install_update",
            // The other half of installing an update. It was in lib.rs's
            // generate_handler! and invoked by settings.js, but never here -
            // which is precisely the failure the comment at the top of this
            // file warns about: registered, reachable from nowhere. The
            // owner installed an update, pressed Restart, and got "not
            // allowed on window" while the new binary sat there unused.
            "restart_app",
            "get_hotkeys",
            "set_hotkeys",
            "reset_hotkeys",
            "hide_widget",
            "resize_desktop_widget",
            "set_widget_always_on_top",
            "save_widget_position",
            "get_widget_prefs",
            "prefill_quickbar",
            "capture_note",
            // How a filed note ended: waiting for approval, filed, or not.
            "capture_note_status",
            // Which note apps this PC is set up for - names only.
            "note_targets",
            // The wiki builder (backend/wiki.patch): read the list, add one
            // document (raises one approval card), follow that job, and
            // open the Jarvis Wiki folder. Brain window only.
            "wiki_status",
            "wiki_ingest",
            "wiki_ingest_status",
            "wiki_open_folder",
            // Deep questions (backend/big-model.patch): read the recent ones
            // and their answers, and ask one. No card per question - the
            // switch was approved - and asking is held on a stale link.
            // Brain window only.
            "get_deep",
            "ask_deep",
            // Quickbar
            "hide_quickbar",
            "resize_quickbar",
            "set_quickbar_pinned",
            "write_clipboard",
            "open_external_url",
            // Diagnostics and startup. Settings window only: the log path is
            // a filesystem path and the startup entry is a registry write,
            // and neither belongs to a page that renders chat.
            "get_log_info",
            "open_log_folder",
            "get_autostart",
            "set_autostart",
            // Shared
            "check_server_health",
            // Push-to-talk voice: real microphone capture, quickbar only —
            // see permissions/surfaces.toml's "voice" set and
            // src-tauri/src/voice.rs's own module docstring.
            "start_voice_capture",
            "stop_voice_capture",
            "cancel_voice_capture",
            "start_automatic_listening",
            "stop_automatic_listening",
            "speak_reply",
            // The HUD's mic button. Shows the quickbar with push-to-talk
            // ready; records nothing. The one command the HUD holds.
            "summon_push_to_talk",
            // Before a screen capture is sent: can the local model see it?
            // Asks the Jarvis server and loopback Ollama; quickbar only.
            "local_model_vision",
        ]));

    // Generates `src-tauri/gen/schemas/*`, embeds the Windows resource and
    // manifest, and makes `tauri::generate_context!()` resolvable.
    tauri_build::try_build(attributes).expect("failed to run tauri-build");
}
