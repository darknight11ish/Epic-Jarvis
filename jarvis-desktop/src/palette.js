/** Fill `{n}` (or any other single key) without a template engine. */
export function fill(text, vars = {}) {
  return String(text).replace(/\{(\w+)\}/g, (whole, key) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : whole);
}

