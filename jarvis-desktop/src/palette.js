/**
 * The heading a row is drawn under. Read off the catalogue's own `area` and
 * `kind`, so a new menu lands in the right heading without an edit here.
 * `area` is one of brain / settings / safety / entry (jarvis_menus.py).
 */
export function headingOf(item) {
  if (item.kind === "entry" || item.area === "safety" || item.area === "entry") {
    return WORDS.group_headings.actions;
  }
  if (item.area === "settings") return WORDS.group_headings.settings;
  if (item.kind === "tab") return WORDS.group_headings.screens;
  return WORDS.group_headings.brain;
}

/**
 * Where one catalogue entry is, in the app: which window it is in, which
 * Brain tab it sits on, and the thing to show once that window is open.
 *
 * `tab` is the Brain view a card sits under - taken from the catalogue's own
 * `view`, which is the same key brain.js's rail uses ("work", "memory", …).
 */
export function entryPlace(m) {
  if (!m) return null;
  // The catalogue's `area` names the window a menu lives in - except for the
  // two "entry" rows (Help, Settings), which are the tray and Brain rows that
  // open the Settings window rather than anything inside the Brain.
  const settings = m.area === "settings" || m.id === "entry.settings" || m.id === "entry.help";
  return {
    id: m.id,
    title: m.title,
    about: m.about || "",
    kind: m.kind,
    area: m.area,
    /** The Brain view key the rail uses ("work", "memory", …); a tab's own
     *  view is itself. A Settings card has none. */
    tab: settings ? "" : (m.view || ""),
    window: settings ? "settings" : "brain",
  };
}

/**
 * The whole list, in the order it should be read: the six named feature
 * groups first (they are what Jarvis itself answers to by voice), then every
 * menu this computer has, in catalogue order.
 *
 * A menu hidden with "Show or hide menus" is left in on purpose: hiding is
 * cosmetic (nothing is turned off), the palette is a way to REACH a menu the
 * owner has tidied away, and a link to a hidden card already shows it for
 * that visit. The row says it is hidden so nothing here is a surprise.
 *
 * @param {{hiddenFor?: (id: string) => boolean}} [deps]
 * @returns {Array<object>}
 */
export function buildPalette({ hiddenFor = () => false } = {}) {
  const items = [];

  for (const g of GROUPS) {
    const mems = members(g.id, APP);
    if (mems.length === 0) continue;
    items.push({
      kind: "group",
      id: g.id,
      title: g.title,
      about: g.about || "",
      /** The names Jarvis already answers to, so typing one finds it. */
      names: Array.isArray(g.names) ? g.names.slice() : [],
      place: { group: true, id: g.id, members: mems },
      hidden: false,
    });
  }

  for (const m of MENUS) {
    if (!has(m, APP)) continue;
    // `safety.*` is not a destination: it is the catalogue's own bookkeeping
    // for things that must never be hidden (approval cards, the stale-link
    // banner, the crisis-help line). None of them is a place a window can
    // open, and offering one would be a row that does nothing the moment it
    // is pressed - the defect this whole audit was about. The row that DOES
    // take the owner there already exists and is listed on its own.
    if (m.area === "safety" && m.kind !== "entry") continue;
    items.push({
      kind: m.kind,
      id: m.id,
      title: m.title,
      about: m.about || "",
      names: Array.isArray(m.names) ? m.names.slice() : [],
      place: entryPlace(m),
      hidden: Boolean(hiddenFor(m.id)),
    });
  }

  return items;
}

/**
 * Case- and punctuation-blind, so "What asks first?" and "what asks first"
 * are the same search. Kept here rather than in the search so the test and
 * the surface always fold the same way.
 */
export function fold(text) {
  return String(text == null ? "" : text)
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/** Where `needle` sits inside `hay`: 0 at the very start, then by word start,
 *  then anywhere. `-1` when it is not there at all. */
function rankAt(hay, needle) {
  if (!hay || !needle) return -1;
  const at = hay.indexOf(needle);
  if (at < 0) return -1;
  if (at === 0) return 0;
  return /[\s-]/.test(hay[at - 1]) ? 1 : 2;
}

/**
 * Ranks one item against an already-folded query. Lower is better; -1 is no
 * match. A title that starts with the words beats a title that contains
 * them, which beats an alias, which beats the one-line description - so
 * typing "work" finds the Work screen first and "network" in a paragraph
 * last.
 */
export function scoreItem(item, query) {
  const q = fold(query);
  if (!q) return 0;
  const title = fold(item.title);
  const titleAt = rankAt(title, q);
  if (titleAt === 0) return 0;
  if (titleAt === 1) return 1;
  if (titleAt === 2) return 2;
  for (const name of item.names || []) {
    const at = rankAt(fold(name), q);
    if (at >= 0) return 3 + at;
  }
  const aboutAt = rankAt(fold(item.about), q);
  if (aboutAt >= 0) return 6 + aboutAt;
  const idAt = rankAt(fold(String(item.id).replace(/\./g, " ")), q);
  if (idAt >= 0) return 9 + idAt;
  return -1;
}

/**
 * The rows the search shows, best first. Ties keep catalogue order, so the
 * list never shuffles between two keystrokes.
 *
 * @param {Array<object>} items  from {@link buildPalette}
 * @param {string} query
 */
export function search(items, query) {
  const q = fold(query);
  if (!q) return items.map((item, index) => ({ item, score: 0, index }));
  const out = [];
  items.forEach((item, index) => {
    const score = scoreItem(item, q);
    if (score >= 0) out.push({ item, score, index });
  });
  out.sort((a, b) =>
    a.score - b.score ||
    a.item.title.length - b.item.title.length ||
    a.index - b.index);
  return out;
}

/**
 * The line a row is announced with and read as its second half. Groups say
 * what they hide; a menu says what it is, and says so when it is hidden on
 * this computer (the same fact the Settings card would show).
 */
export function describe(item) {
  const about = item.about ? item.about : "";
  const hid = item.hidden ? ` Hidden on this computer.` : "";
  if (item.kind === "group") {
    const n = item.place && item.place.members ? item.place.members.length : 0;
    return `${about}${about ? " " : ""}${n === 1 ? "1 menu" : `${n} menus`}.${hid}`.trim();
  }
  return `${about}${hid}`.trim();
}

/**
 * What pressing Enter on a row asks the app to open. This is the shape the
 * two existing navigation mechanisms already take:
 *
 *  * `settings` - the id Settings already uses for that card (settings.js's
 *    own goToPlace, the same path "open <a settings section>" takes);
 *  * `brain` - the view's key and, when the row names a card, the card's own
 *    menu id, which brain.html already carries as `data-menu-id`;
 *  * `group` - the first member, so a group row goes somewhere real rather
 *    than nowhere: the group itself is a hiding unit, not a place.
 *
 * Returns null for anything the app cannot open, and the surface then says
 * so rather than doing nothing.
 */
export function placeFor(item) {
  if (!item) return null;
  if (item.kind === "group") {
    const first = item.place && item.place.members ? item.place.members[0] : null;
    const m = first ? menu(first) : null;
    return m ? placeFor({ id: m.id, kind: m.kind, area: m.area, place: entryPlace(m) }) : null;
  }
  const place = item.place;
  if (!place) return null;
  if (place.window !== "settings" && place.window !== "brain") return null;
  if (place.window === "settings") {
    // `settings.hardware` is Settings -> #hardware. A row that is itself a
    // row of a card (`settings.second-card.referee`) opens its parent card,
    // which is where it lives on the page. The two "entry" rows name their
    // own target instead (Help opens the FAQ card, Settings the window).
    const m = menu(item.id);
    const parent = m && m.parent && m.parent.startsWith("settings.") ? m.parent : null;
    const own = item.id === "entry.help" ? "faq"
      : item.id === "entry.settings" ? "connection" : null;
    const card = parent || own || item.id;
    const elementId = card.startsWith("settings.") ? card.slice("settings.".length) : card;
    return { window: "settings", place: elementId, card };
  }
  const tab = place.tab || "";
  // Which element to show once the window is open. A card is itself; a ROW
  // (kind "row", e.g. `brain.work.quiz.youtube`, `brain.history.tag-suggestions`)
  // has no element of its own, so it opens the nearest card it lives inside -
  // which is where the rail would take the owner by hand. A tab needs no
  // card: the tab is the destination.
  let card = "";
  if (item.kind !== "tab") {
    if (item.kind === "card") {
      card = item.id;
    } else {
      let m = menu(item.id);
      while (m && m.parent) {
        const up = menu(m.parent);
        if (up && up.kind === "card") {
          card = up.id;
          break;
        }
        m = up;
      }
    }
  }
  return card || tab ? { window: "brain", tab, card, place: card || tab } : null;
}

/** True when a row is a feature group rather than one menu. */
export function isGroup(item) {
  return Boolean(item && (item.kind === "group" || isGroupId(item.id)));
}

/** The group a menu belongs to, for a row's own subtitle; "" when it has none. */
export function groupTitleOf(id) {
  const m = menu(id);
  if (!m || !m.group) return "";
  const id2 = m.group.startsWith(GROUP_PREFIX) ? m.group.slice(GROUP_PREFIX.length) : m.group;
  const g = GROUPS.find((x) => x.id === id2 || x.id === GROUP_PREFIX + id2);
  return g ? g.title : "";
}

/** The title the catalogue gives an id - used by tests and by the surface's
 *  own "opened X" line, never a second list of names. */
export function title(id) {
  return titleOf(id);
}
