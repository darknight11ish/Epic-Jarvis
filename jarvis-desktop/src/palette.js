/**
 * palette.js - the words and the list behind the command palette, and
 * nothing that touches a page.
 *
 * WHAT THIS IS FOR. The desktop has 104 menu entries, 33 Settings cards, ten
 * Brain tabs and ten hotkeys, and no way to search any of it: finding one
 * card means opening the right window and knowing which tab it lives on
 * (docs/UI-AUDIT-2026-10-05.md section 2.4, and its "what I would change"
 * row 4 - "build the in-app command palette (already decided, never
 * built)"). This is that palette's list. It offers ONLY what the app can
 * already do: every row is a menu the owner can already reach by hand.
 *
 * WHERE EVERY NAME COMES FROM. THE REAL CATALOGUE, never a second copy.
 * menu-catalog.js is generated by tools/gen_menu_cases.py from
 * backend/jarvis_menus.py, which is the same list "Show or hide menus",
 * Jarvis's own voice and the phone all read. A hand-typed list here would
 * drift from it within a week and send the owner to a card that no longer
 * exists, so there is deliberately no place in this file to type a menu
 * name. Aliases (what Jarvis already answers to) and the `about` line come
 * from the catalogue too.
 *
 * A ROW OPENS WHAT IT SAYS. `placeFor` turns a catalogue id into the place
 * the app already knows how to open - the same two mechanisms the Jarvis bar
 * already uses for "open <a settings section>" and "earlier chats" - and a
 * test walks every row to be sure each one lands somewhere real.
 *
 * NO PAGE, NO TAURI: node can import it (the same rule sayable.js and
 * menu-visibility.js follow), so the list and the search are tested without
 * a browser.
 *
 * @module palette
 */

