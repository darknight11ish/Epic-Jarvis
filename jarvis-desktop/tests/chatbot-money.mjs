/** Code only: `//` and `///` comment lines dropped. A comment that says "this
 *  never carries a key" must not be read as a check that fails. */
function codeOnly(src) {
  return src.split("\n").filter((l) => !/^\s*\/\//.test(l)).join("\n");
}

/** A Rust function's own body, braces counted. */
function rustFn(src, name) {
  const m = new RegExp(
    `\\b(?:pub(?:\\([^)]*\\))?\\s+)?(?:async\\s+)?fn\\s+${name}\\s*[(<]`
  ).exec(src);
  assert.ok(m, `${name} is not in the file`);
  const start = m.index;
  let i = src.indexOf("{", m.index + m[0].length);
  let depth = 0;
  for (let j = i; j < src.length; j += 1) {
    if (src[j] === "{") depth += 1;
    else if (src[j] === "}") {
      depth -= 1;
      if (depth === 0) return src.slice(start, j + 1);
    }
  }
  throw new Error(`${name} has no closing brace`);
}

/** A JavaScript function's own body, braces counted. */
function jsFn(src, name) {
  const m = new RegExp(`(?:async\\s+)?function\\s+${name}\\s*\\(`).exec(src);
  if (!m) return "";
  const start = m.index;
  let i = src.indexOf("{", m.index);
  let depth = 0;
  for (let j = i; j < src.length; j += 1) {
    if (src[j] === "{") depth += 1;
    else if (src[j] === "}") {
      depth -= 1;
      if (depth === 0) return src.slice(start, j + 1);
    }
  }
  throw new Error(`${name} has no closing brace`);
}

