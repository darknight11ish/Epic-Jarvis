/**
 * The monthly money limits and the price list, on the desktop
 * (docs/ACCOUNT-KEYS-DESIGN.md steps 3-5, decisions 1, 3 and 4; the owner's
 * approval of 2026-10-06; src/chatbot-api-keys.js, src/chatbot-api-keys-settings.js,
 * src/settings.html, src-tauri/src/chatbot_money.rs, backend jarvis_chatbot_limits.py).
 *
 * What must hold, and this is the whole point of the feature:
 * - RAISING a limit is a loosening, so the page asks and the PC raises ONE
 *   approval card plus Windows Hello; LOWERING one, removing one, correcting a
 *   price and resetting one need no card. Which of the two it is decided by the
 *   PC from the amount against the limit it holds, never by this page;
 * - the page says which is coming BEFORE the tap, so a wait on a card is never
 *   a surprise, and it shows whichever the PC says actually happened;
 * - every number the page shows comes from the PC's own answer, including
 *   where each price came from ("yours" or "default, unverified") and when it
 *   was set - decision 4's whole point;
 * - CONTROL: the read and the write sit with the Settings window only, both
 *   commands are registered in build.rs and lib.rs, both have an autogenerated
 *   permission file, and the write is held on a stale link;
 * - CONTROL: Rust sends only the five known actions and a service name that
 *   cannot carry a path or a query into the route, and forwards only known
 *   keys - a key can never travel through this route;
 * - CONTROL: the PC's own `pc_only` refusal is passed on as the PC wrote it;
 * - CONTROL: /api/chatbot/money is classified in tools/check_parity.py as
 *   desktop-only, with the reason.
 *
 * The browser-free half runs anywhere, including CI, which has no Playwright.
 */
