/**
 * hud-calendar.mjs - the owner's own calendar in the desktop HUD (2026-10-29).
 *
 *   node tests/hud-calendar.mjs
 *
 * WHAT THIS IS. The owner asked for "a full fledged easy to use calendar built
 * into Jarvis", local only, drawn in the HUD, with month / week / day views, an
 * add and an edit, ON by default and disableable. The store and the four
 * `/api/calendar*` routes are the backend slice's; THIS suite is the desktop
 * half: the card, the sheet, the three views, the one form, the two writes, and
 * the Edit HUD registration the owner made a standing rule ("every easily
 * accessible feature must be addable to the main screen from Edit HUD").
 *
 * HOW IT RUNS WITHOUT A BROWSER. The calendar's script is a block INSIDE
 * jarvis_hud.html (the page is vendored from the backend and must stay
 * byte-identical, so it cannot become a module). This suite therefore takes
 * that exact block out of the page and RUNS it against a tiny fake document -
 * not a copy of its logic, the real thing - so what is asserted here is what
 * the HUD really does. CI's `frontend` job runs this in its Node shards.
 *
 * WHAT IS PROVEN:
 *
 *   1. EVERY STATE IS SAID IN WORDS, never a blank: the feature switched off,
 *      an empty week, a day with nothing on it, a read that failed, and the
 *      locked read. There is no countdown anywhere - a time is a time.
 *   2. the three views really draw: a six-week month grid (Sunday first), the
 *      week's seven columns, and the day's own list; a multi-day event is ONE
 *      bar across the days it covers, with a lane so two never overlap.
 *   3. the ONE form's values become the EXACT argument objects the two Rust
 *      commands take, and the repeat words are the STORE's own
 *      (none/daily/weekly/monthly) - not the schedule's five.
 *   4. the read asks for its window through the shell's allow-list, and the
 *      writes go through `hud_calendar_add` / `hud_calendar_act` only.
 *   5. the card is a real registry card: in CARD_REGISTRY, in MOVABLE_IDS, in
 *      CARD_DOM, in every built-in preset, mirrored in
 *      contract/hud-presets.json - and an owner who ALREADY saved a layout
 *      still gets it back (`withRegistryCards`), which is the half that makes
 *      "addable from Edit HUD" true for him rather than only for a fresh
 *      install.
 *   6. the Rust door: the two commands are in the handler, in build.rs's
 *      manifest, in the HUD's capability and its own permission set; the read
 *      is on hud_proxy's fixed list with its one bounded query; and App lock
 *      blanks the titles, places and notes while keeping the days.
 *   7. the page is still ONE page: the three vendored copies are byte
 *      identical, and no raw JSON is ever put on screen.
 *   8. FAIL CLOSED (2026-10-30): an answer this page does not understand -
 *      `?id=`'s `{"ok": true, "event": {...}}`, a bare event, an array, an
 *      empty body, `available` that is not a boolean, `events` that is not an
 *      array - is refused IN WORDS and draws nothing. It is never read as "an
 *      available calendar with no events", and a write the PC did not confirm
 *      with `{"ok": true}` is never reported as saved.
 *
 * NOT here: the real WebView2 window (a rebuild and install after merge), the
 * store itself (backend/test_local_calendar.py), and a real PC's events.
 */
