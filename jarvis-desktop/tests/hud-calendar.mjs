await check("a multi-day event is ONE bar, clipped to the week, in its own lane", () => {
  const { api } = live;
  const week = api.weekOf("2026-11-04");
  const start = week[1], end = week[3];
  const bars = api.barsFor(week, [event({ date: start, endDate: end })]);
  assert.equal(bars.length, 1);
  assert.equal(bars[0].start, start);
  assert.equal(bars[0].end, end);
  assert.equal(bars[0].span, 3, "the bar does not cover the three days it spans");
  assert.equal(bars[0].col, 1);
  // A bar that runs off the week is CLIPPED and says which end continues.
  const clipped = api.barsFor(week, [event({ date: week[0], endDate: week[5] })]);
  assert.equal(clipped[0].span, 6);
  // Two spanning events on the same days never overlap: they take lanes.
  const two = api.barsFor(week, [
    event({ id: "c0000000001", date: start, endDate: end }),
    event({ id: "c0000000002", date: start, endDate: end }),
  ]);
  assert.equal(two.length, 2);
  assert.notEqual(two[0].lane, two[1].lane, "two bars were drawn in one lane");
});

