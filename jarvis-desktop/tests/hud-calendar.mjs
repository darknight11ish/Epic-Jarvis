/** Every `id="…"` the page's markup carries, so the fake document can answer
 *  `getElementById` honestly instead of for a hand-written list that drifts. */
const IDS = new Set();
for (const match of PAGE.matchAll(/\bid="([a-z0-9-]+)"/g)) IDS.add(match[1]);

function makeNode(tag) {
  return {
    tagName: String(tag || "div").toUpperCase(),
    className: "",
    id: "",
    hidden: false,
    disabled: false,
    checked: false,
    value: "",
    type: "",
    textContent: "",
    children: [],
    style: {},
    dataset: {},
    attrs: {},
    isConnected: true,
    appendChild(child) { this.children.push(child); child.parentNode = this; return child; },
    insertBefore(child, before) {
      const index = before ? this.children.indexOf(before) : -1;
      if (index < 0) this.children.push(child); else this.children.splice(index, 0, child);
      child.parentNode = this;
      return child;
    },
    replaceChildren(...kids) { this.children = []; kids.forEach((kid) => this.appendChild(kid)); },
    remove() {
      if (this.parentNode && this.parentNode.children) {
        const index = this.parentNode.children.indexOf(this);
        if (index >= 0) this.parentNode.children.splice(index, 1);
      }
      this.isConnected = false;
    },
    setAttribute(name, value) { this.attrs[name] = String(value); },
    getAttribute(name) { return name in this.attrs ? this.attrs[name] : null; },
    removeAttribute(name) { delete this.attrs[name]; },
    hasAttribute(name) { return name in this.attrs; },
    addEventListener() {},
    removeEventListener() {},
    focus() {},
    blur() {},
    querySelectorAll() { return []; },
    querySelector() { return null; },
    closest() { return makeNode("div"); },
    contains() { return false; },
  };
}

/** All the text one node holds, in order - what the owner actually reads. */
function words(node) {
  if (!node) return "";
  let out = String(node.textContent || "");
  for (const child of node.children || []) out += ` ${words(child)}`;
  return out.replace(/\s+/g, " ").trim();
}

/** The card's own words: its clock line, its error, its note, its list and the
 *  two buttons. The fake document has no tree, so the parts are named here -
 *  every one of them is a real element of the page's markup. */
const CARD_PARTS = ["cal-card-when", "cal-card-error", "cal-card-note",
  "cal-card-list", "cal-card-actions"];
const PANEL_PARTS = ["cal-banner", "cal-period", "cal-head-when", "cal-grid",
  "cal-week-band", "cal-week-cols", "cal-day-view", "cal-side-list",
  "cal-side-title", "cal-form"];
const textOf = (nodes, ids) => ids.map((id) => words(nodes.get(id)))
  .filter(Boolean).join(" ").replace(/\s+/g, " ").trim();

/** Build the page's calendar block, run it, and hand back its own hook. */
function runCalendar(answer) {
  const nodes = new Map();
  for (const id of IDS) {
    const node = makeNode("div");
    node.id = id;
    nodes.set(id, node);
  }
  // The two the markup carries `hidden` on.
  nodes.get("calendar-panel").hidden = true;
  nodes.get("rail-calendar").hidden = true;

  const document = {
    documentElement: makeNode("html"),
    activeElement: null,
    hidden: false,
    createElement: (tag) => makeNode(tag),
    createTextNode: (text) => ({ nodeType: 3, textContent: String(text), children: [] }),
    getElementById: (id) => nodes.get(id) || null,
    querySelectorAll: () => [],
    querySelector: () => null,
    addEventListener() {},
    removeEventListener() {},
  };
  const window = {
    fetch: () => Promise.resolve({
      ok: answer.ok !== false,
      status: answer.status || 200,
      json: () => Promise.resolve(answer.body),
    }),
    addEventListener() {},
    removeEventListener() {},
  };
  // A closed timer: the block's own 5-minute beat must not be scheduled, or
  // this process would never exit. `refresh` still runs once, immediately.
  const timers = [];
  const setTimeout = (fn, ms) => { timers.push(ms); return timers.length; };
  const clearTimeout = () => {};
  // eslint-disable-next-line no-new-func
  new Function("window", "document", "setTimeout", "clearTimeout", BLOCK)(
    window, document, setTimeout, clearTimeout,
  );
  const api = window.__hudCalendar;
  assert.ok(api, "the page did not expose its calendar hook");
  return { api, nodes, window, document, timers,
    card: () => textOf(nodes, CARD_PARTS),
    panel: () => textOf(nodes, PANEL_PARTS) };
}

/** Let the block's first read finish (it is one promise chain, two steps). */
async function settle(run) {
  for (let i = 0; i < 10; i += 1) await Promise.resolve();
  return run;
}

const pad = (n) => String(n).padStart(2, "0");
const iso = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const NOW = new Date();
const midnight = new Date(NOW.getFullYear(), NOW.getMonth(), NOW.getDate());
const TODAY = iso(midnight);
const plus = (days) => {
  const d = new Date(midnight.getTime());
  d.setDate(d.getDate() + days);
  return iso(d);
};

/** A timed event that has NOT started yet, whatever time this suite runs at -
 *  a fixed "14:30 today" is in the past for anyone running it in the evening,
 *  and the card's whole job is to show what is still to come. */
/* "Soon" must be TODAY and still ahead - the card lists today's remaining
   events. The first version was `NOW + 90 min` with its 45-minute END on
   today's date too, and it broke twice over: from 21:45Z the end rolled to
   00:xx while its date stayed today, so the card (correctly) read the event as
   already ended and dropped it - and from 22:30Z the start itself was on
   tomorrow. Both are fixed: the start is clamped to today with a minute to
   spare, the end carries the END's own date, and the clamp is proved over every
   hour of a fake day so this cannot come back at one particular hour. */
const endOfToday = midnight.getTime() + 24 * 60 * 60000;
const SOON_MS = Math.min(NOW.getTime() + 90 * 60000, endOfToday - 60000);
const SOON = new Date(SOON_MS);
const SOON_DATE = iso(SOON);
const SOON_TIME = `${pad(SOON.getHours())}:${pad(SOON.getMinutes())}`;
const SOON_END = `${pad(new Date(SOON.getTime() + 45 * 60000).getHours())}:`
  + `${pad(new Date(SOON.getTime() + 45 * 60000).getMinutes())}`;
/* The END's own date, not the start's: an event that starts near midnight ends
   on the NEXT day, and the fixture has to say so - otherwise the card rightly
   reads its 00:xx end on today's date as already past and drops the event. */
const SOON_END_DATE = iso(new Date(SOON.getTime() + 45 * 60000));
for (let hour = 0; hour < 24; hour += 1) {
  const fakeNow = new Date(midnight.getTime() + hour * 60 * 60000 + 30 * 60000);
  const fakeMidnight = new Date(fakeNow.getFullYear(), fakeNow.getMonth(), fakeNow.getDate());
  const fakeEnd = fakeMidnight.getTime() + 24 * 60 * 60000;
  const fakeSoon = Math.min(fakeNow.getTime() + 90 * 60000, fakeEnd - 60000);
  if (iso(new Date(fakeSoon)) !== iso(fakeNow)) {
    throw new Error(`the "soon" fixture leaves today at ${hour}:30 - the card would `
      + "not list it, which is what CI hit at 22:00 UTC");
  }
}

