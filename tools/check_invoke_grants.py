#!/usr/bin/env python3
"""Every command a page calls must be granted to the window that shows it.

    python3 tools/check_invoke_grants.py [-v]

This is the check for a whole class of bug this tree has already shipped:
a feature whose button calls a Tauri command the ACL does not grant, so the
call is refused at runtime and the button silently does nothing - no compile
error, no test failure, just a control that never works. Two of them are in
this tree today and are exactly what this script exists to print:

  * `brain.js`'s "Hidden menus" button calls `open_fix_place`, which lives in
    `surfaces.toml` under the quickbar's own set. The Brain's capability never
    grants it, so the button was dead in the window that draws it.
  * `brain.js` calls the four `brain_quiz_cloud_*` commands, each of which has
    a generated permission file under permissions/autogenerated/ and no grant
    in any set at all: every window's call is refused.

Nothing before this script compared the two halves. `tools/check_command_acl.py`
checks that a command registered in lib.rs has a permission FILE, which is
necessary and not sufficient: the file also has to be in a set, and the set has
to be granted to the capability of the window whose page makes the call.

What it reads - all from THIS checkout:

  jarvis-desktop/src/**/*.js, *.html   the pages and the modules they load
  src-tauri/permissions/surfaces.toml  the sets, and the allow-* in each
  src-tauri/capabilities/*.json        which window is granted which set
  src-tauri/tauri.conf.json            the two windows declared there
  src-tauri/src/**/*.rs                every other window, and the page it
                                        loads (WebviewWindowBuilder)

Two things it cannot decide, both of which it says out loud rather than
guessing:

  * a command NAME built at runtime (`invoke(command)`). The call site is
    listed in DYNAMIC_BELOW with a one-line reason, so a new one has to be
    added deliberately rather than arriving unnoticed.
  * a module loaded by more than one window (`jarvis-link.js` is loaded by
    seven of them). One window's capability cannot judge the whole file, so
    only the parts the window's OWN code calls are judged against it. The
    count is printed so the gap stays visible.
"""
