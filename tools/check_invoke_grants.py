def sets_from_surfaces() -> dict[str, set[str]]:
    text = (SRC_TAURI / "permissions" / "surfaces.toml").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r'\[\[set\]\]\s*identifier\s*=\s*"([^"]+)"(.*?)(?=\n\[\[set\]\]|\Z)',
                         text, re.S):
        out[m.group(1)] = set(re.findall(r'"(allow-[a-z0-9-]+)"', m.group(2)))
    return out


def capabilities() -> dict[str, tuple[tuple[str, ...], set[str]]]:
    out = {}
    for path in sorted((SRC_TAURI / "capabilities").glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        out[path.stem] = (tuple(doc.get("windows") or ()), set(doc.get("permissions") or ()))
    return out


def windows_to_pages() -> dict[str, str]:
    """label -> the page that window loads.

    The two windows in tauri.conf.json are declared there; every other one is
    built in Rust by `WebviewWindowBuilder::new(app, LABEL, WebviewUrl::App(
    "page.html"))`. The label is usually a constant, and two modules each
    define their own `BADGE_LABEL` meaning different windows - so constants are
    resolved per file, never in one pool.
    """
    out: dict[str, str] = {}
    for path in sorted((SRC_TAURI / "src").rglob("*.rs")):
        text = path.read_text(encoding="utf-8", errors="replace")
        consts = dict(re.findall(r'const\s+([A-Z_][A-Z0-9_]*)\s*:\s*&str\s*=\s*"([^"]+)"', text))
        for m in re.finditer(r"WebviewWindowBuilder::new\s*\(", text):
            call = text[m.end() - 1:text.find(".build()", m.end()) if ".build()" in text else m.end() + 4000]
            args = arguments(call, 0)
            if len(args) < 3:
                continue
            label = args[1].strip()
            label = consts.get(label, label.strip('"'))
            direct = re.search(r'WebviewUrl::App\(\s*"([^"]+)"', call)
            if direct:
                page = direct.group(1)
            else:
                # The Brain does not write its page inside the builder: it
                # builds `let page = match place { Some(p) =>
                # format!("brain.html#{p}"), None => "brain.html" }` a few
                # lines above and passes the variable. Take the last page name
                # written before the builder - and where there is none, main()
                # says so rather than quietly judging no calls for that window.
                before = text[max(0, m.start() - 600):m.start()]
                found = re.findall(r'"([\w.-]+\.html)', before)
                page = found[-1] if found else None
            if page:
                out[label] = page.split("#")[0]
    conf = json.loads((SRC_TAURI / "tauri.conf.json").read_text(encoding="utf-8"))
    for window in conf.get("app", {}).get("windows", []):
        out.setdefault(window["label"], window["url"])
    return out


# ---------------------------------------------------------------------------
#   Reading the pages: which module each one loads
# ---------------------------------------------------------------------------

def imports_of(text: str) -> set[str]:
    return set(re.findall(r'from\s+"\./([\w.-]+\.js)"', text)) | \
        set(re.findall(r'import\(\s*"\./([\w.-]+\.js)"\s*\)', text))


def read(name: str) -> str:
    path = SRC / name
    return path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""


def modules_of(page: str) -> set[str]:
    """Every module a page loads, following imports from the page itself."""
    seen: set[str] = set()
    stack = list(set(re.findall(r'<script[^>]*\bsrc="([^"]+)"', read(page))) | imports_of(read(page)))
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        seen.add(name)
        stack.extend(imports_of(read(name)))
    return seen


def called_from(module: str, owner: str, texts: list[str]) -> bool:
    """Does any ONE of these files CALL `owner`, one of `module`'s exports?

    Under its imported name, never by bare word, and within the file that
    does the importing. Both halves matter:
      * `decide` is jarvis-link.js's approval decision AND the name of an
        unrelated pacing function in face-pace.js, and faces.html writes
        `FacePace.decide(...)` - matching the word alone reported the Faces
        window as answering approvals it has no UI to answer;
      * the widget defines its OWN `decide(approved)` while importing
        `amend as amendOnBackend` from jarvis-link.js - pooling every file of
        a page into one blob paired that import with the wrong call, and
        reported the widget as deciding approvals it decides locally.
    So the name has to be imported FROM THIS MODULE, in this file, as a
    destructured binding (`import { decide } from "./jarvis-link.js"`) or
    through a namespace (`import * as link from ...`), and then called here.
    """
    for text in texts:
        for m in re.finditer(r'import\s*\{([^}]*)\}\s*from\s*"\./' + re.escape(module) + r'"', text):
            for part in m.group(1).split(","):
                bits = [b.strip() for b in part.split(" as ")]
                if len(bits) < 1 or not bits[0]:
                    continue
                # The EXPORT is what has to match: brain.js imports `announce`
                # and calls it, and pairing that with `setMuted`'s own name
                # alone flagged every function in the module for every page
                # that imported anything from it at all.
                if bits[0] == owner and re.search(r"(?<![\w$.])" + re.escape(bits[-1]) + r"\s*\(", text):
                    return True
        for m in re.finditer(r'import\s*\*\s*as\s+([\w$]+)\s*from\s*"\./' + re.escape(module) + r'"', text):
            if re.search(re.escape(m.group(1)) + r"\s*\.\s*" + re.escape(owner) + r"\s*\(", text):
                return True
    return False


def granted_anywhere() -> set[str]:
    text = (SRC_TAURI / "permissions" / "surfaces.toml").read_text(encoding="utf-8")
    names = set(re.findall(r'"(allow-[a-z0-9-]+)"', text))
    for path in (SRC_TAURI / "capabilities").glob("*.json"):
        names |= set(re.findall(r'"(allow-[a-z0-9-]+)"', path.read_text(encoding="utf-8")))
    return names


def main() -> int:
    verbose = "-v" in sys.argv
    sets = sets_from_surfaces()
    caps = capabilities()
    label_page = windows_to_pages()
    any_grant = granted_anywhere()

    granted: dict[str, set[str]] = {}
    page_cap: dict[str, str] = {}
    problems: list[str] = []
    for cap, (labels, permissions) in caps.items():
        allowed: set[str] = set()
        for name in permissions:
            if name.startswith("core:"):
                continue
            allowed |= sets.get(name, set())
            if name.startswith("allow-"):
                allowed.add(name)
        for label in labels:
            granted[label] = allowed
            page = label_page.get(label)
            if page is None:
                problems.append(f"::error::capabilities/{cap}.json grants window "
                                f"{label!r}, but nothing here says which page it "
                                f"loads - this check cannot judge its calls")
            else:
                page_cap.setdefault(page, cap)

    pages = sorted(p.name for p in SRC.glob("*.html"))
    files = sorted(str(p.relative_to(SRC)).replace("\\", "/")
                   for p in SRC.rglob("*") if p.suffix in (".js", ".html"))
    loads: dict[str, int] = {}
    for page in pages:
        for name in modules_of(page):
            loads[name] = loads.get(name, 0) + 1
    shared = {name for name, n in loads.items() if n > 1}
    pages_of: dict[str, list[str]] = {}
    for label, page in label_page.items():
        pages_of.setdefault(page, []).append(label)

    checked: set[str] = set()
    violations: list[tuple[str, str, int, str, str | None]] = []
    dynamic: list[tuple[str, int, str, str]] = []

    for page in pages:
        cap = page_cap.get(page)
        # What THIS window is allowed to call - the whole point of the check.
        # `any_grant` below is the weaker "some set, somewhere" question, and
        # using it here is exactly how `open_fix_place` (granted to the
        # quickbar alone) looked fine from the Brain.
        allowed: set[str] = set()
        for label in pages_of.get(page, []):
            allowed |= granted.get(label, set())
        local = [name for name in modules_of(page) if name not in shared] + [page]
        local_text = [read(name) for name in local]
        for name in sorted(modules_of(page) | {page}):
            text = read(name)
            if not text:
                continue
            owners = blocks(text)
            for line, at, arg in calls(text):
                names, opaque = command_names(arg)
                if opaque:
                    dynamic.append((name, line, arg, page))
                    continue
                if name in shared:
                    # One window's capability cannot judge a module seven of
                    # them load: only what THIS page's own code reaches counts.
                    owner = next((b[0] for b in owners if b[1] <= at <= b[2]), None)
                    if owner is not None and not called_from(name, owner, local_text):
                        continue
                for command in names:
                    checked.add(command)
                    if not any_grant:
                        continue
                    permission = "allow-" + command.replace("_", "-")
                    if permission in allowed:
                        continue
                    violations.append((name, page, line, command, cap))

    # Every name the pages call anywhere, so a command with a permission file
    # and no grant is named even where the window itself looks fine.
    everywhere: dict[str, list[str]] = {}
    for name in files:
        text = read(name)
        if not text:
            continue
        for line, _at, arg in calls(text):
            names, opaque = command_names(arg)
            for command in names:
                everywhere.setdefault(command, []).append(f"{name}:{line}")

    ungranted = sorted(n for n in everywhere if "allow-" + n.replace("_", "-") not in any_grant)

    unknown_dynamic = sorted({(f, a) for f, _l, a, _p in dynamic if (f, a) not in DYNAMIC_BELOW})

    for line in problems:
        print(line)
    if ungranted:
        print("::error::Called by a page but granted by no set in surfaces.toml "
              "or capabilities/*.json - every window's call to it is refused:")
        for command in ungranted:
            where = ", ".join(everywhere[command][:3])
            print(f"  {command}  ({where})")
    if violations:
        print("::error::Called from a window whose capability does not grant it - "
              "the control that calls it does nothing, silently:")
        for name, page, line, command, cap in violations:
            where = f"capability {cap}" if cap else "no capability"
            print(f"  {command}  ({name}:{line}, reached from {page}; "
                  f"{where} has no allow-{command.replace('_', '-')})")
    if unknown_dynamic:
        print("::error::Called with a name built at runtime, and not on this "
              "script's own DYNAMIC_BELOW list - add it there with a one-line "
              "reason, or make the name a literal:")
        for name, arg in unknown_dynamic:
            print(f"  {name}  invoke({arg})")

    if problems or ungranted or violations or unknown_dynamic:
        return 1

    print(f"{len(everywhere)} command(s) invoked from {len(pages)} page(s); every one is "
          f"granted by the window whose page calls it.")
    print(f"{len(DYNAMIC_BELOW)} call site(s) pass a name built at runtime, each listed "
          f"in this script with its reason.")
    if shared:
        print(f"{len(shared)} module(s) are loaded by more than one window, so their calls "
              f"are judged only where the window's own code reaches them "
              f"({', '.join(sorted(shared)[:4])}, ...).")
    if verbose:
        for page in pages:
            print(f"  {page:<20} {len(modules_of(page)):>3} module(s), "
                  f"capability {page_cap.get(page, '(none)')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
