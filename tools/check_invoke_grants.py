# ---------------------------------------------------------------------------
#   Reading the pages: what is code, and what is only text that looks like it
# ---------------------------------------------------------------------------

def code_mask(src: str) -> list[bool]:
    """True at each offset that is real JavaScript, False inside a comment, a
    string, a template's text or a regex literal.

    Without this, a page's own log line - `console.error(`[jarvis] invoke(
    "${command}") failed:`)` - reads as a call to a command called
    `${command}`, and the console message would have to be listed as a
    dynamically built name. Offsets are untouched, so reported line numbers
    still point at the real line (the same trick as check-tokens.py).
    """
    mask = [True] * len(src)
    i, n = 0, len(src)
    prev = ""            # last real code character, for the regex-literal guess
    while i < n:
        c = src[i]
        if c == "/" and i + 1 < n and src[i + 1] == "/":
            while i < n and src[i] != "\n":
                mask[i] = False
                i += 1
        elif c == "/" and i + 1 < n and src[i + 1] == "*":
            end = src.find("*/", i + 2)
            end = n if end < 0 else end + 2
            for j in range(i, end):
                if src[j] != "\n":
                    mask[j] = False
            i = end
        elif c in "\"'`":
            quote = c
            i += 1
            while i < n:
                if src[i] == "\\":
                    mask[i] = False
                    i += 2
                    continue
                if src[i] == quote:
                    i += 1
                    break
                if quote == "`" and src[i] == "$" and i + 1 < n and src[i + 1] == "{":
                    # ${ ... } is code again: skip the balanced braces, leaving
                    # the mask alone inside them.
                    depth = 1
                    i += 2
                    while i < n and depth:
                        if src[i] == "{":
                            depth += 1
                        elif src[i] == "}":
                            depth -= 1
                        i += 1
                    continue
                if src[i] != "\n":
                    mask[i] = False
                i += 1
        elif c == "/" and prev in "(,=:[!&|?{};+-*%~^<>" and not src.startswith("/=", i):
            i += 1
            while i < n and src[i] != "\n":
                if src[i] == "\\":
                    i += 1
                elif src[i] == "/":
                    i += 1
                    break
                i += 1
        else:
            if not c.isspace():
                prev = c
            i += 1
    return mask


def arguments(src: str, start: int) -> list[str]:
    """The top-level arguments of the call whose `(` is at `start`.

    Scanning begins just past that `(`, or every comma inside the call reads as
    nested one level too deep and the first "argument" comes back as the whole
    call: that is how `invoke("browser_engine", { action: "read" })` was read
    as a command called `read`.
    """
    out, depth, i, begin = [], 1, start + 1, start + 1
    while i < len(src) and depth:
        c = src[i]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                break
        elif c == "," and depth == 1:
            out.append(src[begin:i])
            begin = i + 1
        i += 1
    out.append(src[begin:i])
    return out


def blocks(src: str) -> list[tuple[str, int, int]]:
    """(name, start, end) for each top-level function or arrow const, so a call
    inside a shared module can be attributed to the name a page would call."""
    out = []
    for m in re.finditer(r"^(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)",
                         src, re.M):
        brace = src.find("{", m.end())
        if brace > 0:
            out.append((m.group(1), m.start(), _close(src, brace)))
    for m in re.finditer(r"^(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=", src, re.M):
        end = src.find("\n", m.end())
        # An arrow or a function expression keeps going to its closing brace.
        arrow = re.search(r"=>\s*\{", src[m.end():m.end() + 200])
        if arrow:
            end = _close(src, m.end() + arrow.end() - 1)
        out.append((m.group(1), m.start(), end))
    return sorted(out, key=lambda b: b[1])


def _close(src: str, brace: int) -> int:
    depth, i = 0, brace
    while i < len(src):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(src) - 1


def functions(src: str) -> list[tuple[str, list[str], int, int]]:
    """(name, parameters, definition start, definition end) for each function
    this file defines, whichever of the two shapes it is written in.

    The span starts at the definition rather than at its `{`, so that a call
    scan can tell `function invoke(command)` - the definition - from
    `invoke("get_theme")`, a call.
    """
    out = []
    for m in re.finditer(r"(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)", src):
        brace = src.find("{", m.end())
        if brace < 0:
            continue
        out.append((m.group(1), _params(m.group(2)), m.start(), _close(src, brace)))
    for m in re.finditer(r"(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=", src):
        # The arrow is not always the first thing after the `=`: sky-feed.js
        # writes `const call = invoke || (IS_TAURI ? (c, a) => ...invoke(c, a)
        # : null)`, and the name a page calls is still `call`. A head carrying
        # a `{` is an object literal whose member is the arrow - not this
        # name - so it is refused rather than guessed at.
        head = src[m.end():m.end() + 200]
        arrow = re.search(r"\(([^)]*)\)\s*=>", head)
        if not arrow or re.search(r"[{};]", head[:arrow.start()]):
            continue
        brace = src.find("{", m.end() + arrow.end())
        if brace < 0 or brace > m.end() + 400:
            continue
        out.append((m.group(1), _params(arrow.group(1)), m.start(), _close(src, brace)))
    return out


def _params(text: str) -> list[str]:
    return [p.strip().split("=")[0].strip() for p in text.split(",") if p.strip()]


def helpers(src: str, mask: list[bool]) -> dict[str, tuple[int, int]]:
    """{function name: (definition start, definition end)} for every function
    that hands a command name of its own on to the IPC - directly, or through
    another such function.

    This is what makes the check reach the commands behind the wrappers.
    Every page keeps one `invoke(command, args)`, so its real call sites read
    `invoke("get_theme")`; reading only `TAURI.core.invoke(...)` would have
    missed all four `brain_quiz_cloud_*` calls and a hundred others. brain.js
    then adds a SECOND layer - `topicsCall(cmd, args)`, `chatbotAct(cmd,
    args)`, `decksCall(cmd, args)` and friends - and following only the bottom
    layer would leave every `topicsCall("brain_topics_mode")` unchecked, which
    is the same class of bug one level down.
    """
    defs = functions(src)
    found: dict[str, tuple[int, int]] = {}
    for _ in range(3):                       # a chain this deep is a rewrite
        added = False
        for name, params, begin, end in defs:
            if name in found or not params:
                continue
            body = src[begin:end + 1]
            by = None
            call = INVOKE.search(body)
            if call:
                by = arguments(body, call.end() - 1)
            for other in found:
                call = re.search(r"(?<![\w$.])" + re.escape(other) + r"\s*\(", body)
                if by is None and call:
                    by = arguments(body, call.end() - 1)
            if by and by[0].strip() == params[0]:
                found[name] = (begin, end)
                added = True
        if not added:
            break
    return found


def calls(src: str) -> list[tuple[int, int, str]]:
    """(line, offset, first argument as written) for every IPC call site.

    Both spellings count: `TAURI.core.invoke("name", ...)`, and a call to one
    of the file's own forwarding helpers with a literal first argument.
    """
    mask = code_mask(src)
    found = [(m.start(), arguments(src, m.end() - 1))
             for m in INVOKE.finditer(src) if mask[m.start()]]
    for name, (begin, end) in helpers(src, mask).items():
        for c in re.finditer(r"(?<![\w$.])" + re.escape(name) + r"\s*\(", src):
            if not mask[c.start()] or begin <= c.start() <= end:
                continue                     # the definition, not a call
            found.append((c.start(), arguments(src, c.end() - 1)))
    out = []
    for at, args in sorted(found):
        if args:
            out.append((src[:at].count("\n") + 1, at, args[0].strip()))
    return out


def command_names(arg: str) -> tuple[list[str], bool]:
    """The command names a call site can reach, and whether it is opaque.

    `"get_theme"` is one name. `fromServer ? "get_appearance" :
    "appearance_snapshot"` is two - that is a choice between two commands, not
    a name built at runtime, and both need a grant. `command` is neither: it
    is the dynamic case, and the allow-list above is what makes it deliberate.
    """
    one = re.fullmatch(r'"([a-z0-9_]+)"', arg)
    if one:
        return [one.group(1)], False
    names = [s for s in re.findall(r'"([a-z0-9_]+)"', arg) if re.fullmatch(r"[a-z][a-z0-9_]*", s)]
    if names:
        return names, False
    return [], True


# ---------------------------------------------------------------------------
