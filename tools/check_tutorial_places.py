def _as_dict(node):
    """A `{...}` literal in the tutorials file as {key: value node}, or None.

    Read from the syntax tree rather than `ast.literal_eval` so the line each
    `where` string is written on comes back with it: a finding the owner cannot
    jump to is half a finding.
    """
    if not isinstance(node, ast.Dict):
        return None
    out = {}
    for key, value in zip(node.keys, node.values):
        if isinstance(key, ast.Constant) and isinstance(key.value, str):
            out.setdefault(key.value, value)
    return out


def _string(node):
    """The string a node is, or None when it is anything else."""
    return node.value if isinstance(node, ast.Constant) and \
        isinstance(node.value, str) else None


def tutorial_wheres(path: Path):
    """([(kind, id, step, where, line)], why it could not be read).

    The two tuples the module really defines, `CATALOGUE` and `FAQ`, taken from
    its own `ast` - so this reads the file the apps are served from, and a file
    that has been renamed, emptied or broken is a failure here rather than a
    quiet pass over nothing.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as err:
        return [], f"{path} could not be read ({err})"
    try:
        tree = ast.parse(text)
    except SyntaxError as err:
        return [], f"{path} is not Python (line {err.lineno}: {err.msg})"

    literals: dict[str, ast.AST] = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id in ("CATALOGUE", "FAQ"):
                literals[target.id] = node.value

    out: list[tuple[str, str, int, str, int]] = []

    catalogue = literals.get("CATALOGUE")
    if catalogue is None:
        return [], (f"{path} defines no CATALOGUE - this check reads the real "
                    f"file, and a file without it is not the file to read")
    if not isinstance(catalogue, ast.Tuple):
        return [], f"{path}: CATALOGUE is not a tuple of tutorials"
    for index, tutorial in enumerate(catalogue.elts, 1):
        entry = _as_dict(tutorial)
        if entry is None:
            return [], f"{path}: tutorial #{index} in CATALOGUE is not a dict"
        entry_id = _string(entry.get("id")) or f"#{index}"
        steps = entry.get("steps")
        if not isinstance(steps, ast.Tuple):
            return [], f"{path}: tutorial `{entry_id}` has no `steps` tuple"
        for number, step in enumerate(steps.elts, 1):
            fields = _as_dict(step)
            if fields is None:
                return [], (f"{path}: step {number} of `{entry_id}` is not a "
                            f"dict")
            where = fields.get("where")
            if where is None:
                continue
            value = _string(where)
            if value is None:
                return [], (f"{path}: step {number} of `{entry_id}` has a "
                            f"`where` that is not a string")
            out.append(("tutorial", entry_id, number, value, where.lineno))

    faq = literals.get("FAQ")
    if isinstance(faq, ast.Tuple):
        for number, question in enumerate(faq.elts, 1):
            fields = _as_dict(question)
            if fields is None:
                return [], f"{path}: FAQ item {number} is not a dict"
            where = fields.get("where")
            if where is None:
                continue
            value = _string(where)
            if value is None:
                return [], (f"{path}: FAQ item {number} has a `where` that is "
                            f"not a string")
            out.append(("faq", "faq", number, value, where.lineno))
    return out, ""


