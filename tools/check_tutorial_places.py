def main() -> int:
    verbose = "-v" in sys.argv
    catalogue = CATALOGUE_PY
    if "--catalogue" in sys.argv:
        # A way to exercise this check against a copy, on purpose - the same
        # door check_literal_keys.py leaves open with --no-git. It is said out
        # loud, so a run that read some other file can never look like a run
        # that read the real one.
        at = sys.argv.index("--catalogue")
        if at + 1 >= len(sys.argv):
            print("::error::--catalogue needs a path after it")
            return 1
        catalogue = Path(sys.argv[at + 1]).resolve()
        print(f"::warning::reading `{catalogue}` instead of "
              f"`{CATALOGUE_PY}` (--catalogue) - this run does NOT say anything "
              f"about the file CI reads.")

    wheres, problem = tutorial_wheres(catalogue)
    if problem:
        print(f"::error::{problem}")
        return 1
    if not wheres:
        print(f"::error::{catalogue} holds no `where` line at all - a check that "
              f"reads nothing must not pass")
        return 1
    # The file the findings are reported against. Normally the real one, so a
    # finding reads `backend/jarvis_tutorials.py:140`; under --catalogue it is
    # the copy, so the output never claims to be about a file it did not read.
    shown = (catalogue.relative_to(REPO).as_posix()
             if catalogue.is_relative_to(REPO) else str(catalogue))

    known, trouble = load_known_names()
    if trouble:
        print(f"::error::the names the apps have could not all be read, so a "
              f"finding below may only mean this check could not see the app: "
              f"{trouble}")
        return 1
    if not known:
        print("::error::read no UI name from either app - this check would pass "
              "having checked nothing")
        return 1

    chains_seen = sum(1 for _kind, _id, _step, where, _line in wheres
                      if has_arrow(where))
    checked = 0
    missing: list[tuple[str, str, int, int, str, str, str]] = []
    for kind, entry_id, step, where, line in wheres:
        for piece, name in named_places(where):
            checked += 1
            if normalise(name) in known:
                continue
            missing.append((kind, entry_id, step, line, where, piece, name))

    # Every recorded entry this run actually reports, and every unrecorded
    # finding. The first list is printed whether or not the run is otherwise
    # green; the second one is what sets the exit code.
    recorded: dict[tuple, tuple[str, str, int, int, str, str]] = {}
    unrecorded: list[tuple[str, str, int, int, str, str, str]] = []
    for finding in missing:
        kind, entry_id, step, line, where, piece, name = finding
        if known_drift(kind, entry_id, step, piece) is None:
            unrecorded.append(finding)
        else:
            recorded[(kind, entry_id, step, piece)] = finding
    stale = [key for key in KNOWN_DRIFT if key not in recorded]

    problems = bool(unrecorded or stale)

    if unrecorded:
        print("::error::a tutorial's `where` line sends the owner to a name "
              "neither app has. Read each one and either fix the wording or "
              "record it in KNOWN_DRIFT, with the reason it cannot be fixed "
              "here and where the fix belongs - a finding NOT recorded below "
              "exits 1:")
        for kind, entry_id, step, line, where, piece, name in sorted(
                unrecorded, key=lambda f: (f[0], f[1], f[2], f[5])):
            who = (f"the `{entry_id}` tutorial, step {step}" if kind == "tutorial"
                   else f"FAQ question {step}")
            print(f"  {shown}:{line}  {who} names `{piece}`")
            print(f"      its `where` line reads: {where}")
            if piece != name:
                print(f"      (the name to look for there is `{name}`)")
            print(f"      neither app's menus, headings, buttons, item keys or "
                  f"screens carry that name")

    if stale:
        print("::error::a name recorded in KNOWN_DRIFT was NOT reported by this "
              "run - delete the entry if the wording is fixed, or move it to "
              "where the line is now, because a stale entry is the one way this "
              "list could quietly absorb a real finding:")
        for kind, entry_id, step, piece in sorted(
                stale, key=lambda k: (k[0], k[1], k[2], k[3])):
            who = (f"the `{entry_id}` tutorial, step {step}" if kind == "tutorial"
                   else f"FAQ question {step}")
            print(f"  {who} no longer names `{piece}` - recorded, not reported")

    if recorded:
        # Printed whether or not the rest of the run is green, because the whole
        # point of a recorded name is that it stays visible. A recorded name
        # that is never printed is an ignore list with extra steps.
        print()
        print("these `where` lines name something the apps do not have. They are "
              "recorded in KNOWN_DRIFT, so they do not fail this check, and they "
              "are printed on every run so they cannot be forgotten:")
        for key in sorted(recorded, key=lambda k: (k[0], k[1], k[2], k[3])):
            kind, entry_id, step, piece = key
            _k, _i, _s, line, where, _piece, judged = recorded[key]
            who = (f"the `{entry_id}` tutorial, step {step}" if kind == "tutorial"
                   else f"FAQ question {step}")
            print(f"  {shown}:{line}  {who} names `{piece}`")
            print(f"      its `where` line reads: {where}")
            if piece != judged:
                print(f"      (the name to look for there is `{judged}`)")
            print(f"      cannot be fixed here: {KNOWN_DRIFT[key].reason}")
            print(f"      the fix belongs: {KNOWN_DRIFT[key].fix}")

    if verbose:
        print(f"  tutorials and FAQ read from: {catalogue}")
        print(f"  {chains_seen} of the {len(wheres)} `where` line(s) carry a "
              f"breadcrumb, and {len(wheres) - chains_seen} do not")
        print(f"  {checked} name-shaped piece(s) judged against {len(known)} "
              f"name(s) the apps have")
        print(f"  names read from: {MENU_JS.name}, every *.html under "
              f"{DESKTOP_SRC.name}/, every *.js `title:`, `*_LABEL`/`*_TITLE`, "
              f"`node(...)` text and WORDS/LABELS table there, {MENU_KT.name}, "
              f"{PLACES_KT.name}, {NAV_KT.name}, GroupHeading(...) under "
              f"ui/screens/, every `title = \"...\"` under {PHONE_UI.name}/ and "
              f"every `*_TITLE`/`*_LABEL`/`*_NAME` constant in the phone's code")

    if problems:
        return 1

    print(f"{len(wheres)} `where` line(s) read from "
          f"{catalogue.relative_to(REPO).as_posix() if catalogue.is_relative_to(REPO) else catalogue}; "
          f"{chains_seen} of them carry a breadcrumb, and every one of the "
          f"{checked} name(s) in those breadcrumbs is a name the apps really "
          f"have.")
    print("The names were matched exactly against the desktop's generated menu "
          "catalogue, its pages' headings and buttons and its modules' own "
          "labels, and the phone's menu catalogue, screen names, item keys, "
          "group headings and plate titles - no substring search and no fuzzy "
          "match.")
    if recorded:
        print(f"{len(recorded)} known drift(s) reported, each recorded in "
              f"KNOWN_DRIFT with its reason; a name NOT recorded there still "
              f"exits 1.")
    else:
        print("No recorded drift was reported by this run.")
    print("NOT checked, on purpose: a `where` line with no `->` in it (a "
          "sentence, where a name cannot be told from prose), and whether a real "
          "name is on the right screen or in the right app. A wrong name written "
          "either of those ways still passes this check.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
