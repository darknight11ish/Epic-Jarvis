def _json_export(text: str, name: str):
    """The JSON literal written after `export const NAME =`, or None.

    The generated catalogue is JSON inside a JS file - quoted keys, arrays,
    nulls - so it is read by the JSON parser rather than by a regex. The span is
    found by walking brackets, which is the only thing that survives the
    strings in it holding braces of their own.
    """
    at = text.find(f"export const {name} =")
    if at < 0:
        return None
    start = min((i for i in (text.find("[", at), text.find("{", at)) if i >= 0),
                default=-1)
    if start < 0:
        return None
    depth, i, n = 0, start, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            i += 1
            while i < n:
                if text[i] == "\\":
                    i += 2
                    continue
                if text[i] == '"':
                    break
                i += 1
        elif c in "[{":
            depth += 1
        elif c in "]}":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(text[start:i + 1])
                except ValueError:
                    return None
        i += 1
    return None


def _balanced_text(text: str, open_at: int) -> str:
    """The text of the bracket pair opened at `open_at`, itself included.

    Strings are stepped over rather than counted, because a label in one of
    these tables may hold a brace of its own.
    """
    depth, i, n = 0, open_at, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            i += 1
            while i < n:
                if text[i] == "\\":
                    i += 2
                    continue
                if text[i] == '"':
                    break
                i += 1
        elif c in "[{":
            depth += 1
        elif c in "]}":
            depth -= 1
            if depth == 0:
                return text[open_at:i + 1]
        i += 1
    return text[open_at:]


def names_from_menu_catalogue(path: Path):
    """Every name the shared menu catalogue carries, plus why it failed.

    Four things are names here, and all four are the app's own words for a
    thing: the menu's `title` (what is drawn), its `id` (what the code calls
    it), the `names` it answers to, and the group `title`. The aliases are the
    same list from the other side, so they are folded in with them.
    """
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError as err:
        return [], f"{path} could not be read ({err})"
    if not text:
        return [], f"{path} is empty"

    found: list[str] = []
    menus = _json_export(text, "MENUS")
    groups = _json_export(text, "GROUPS")
    aliases = _json_export(text, "ALIASES")
    if not isinstance(menus, list) or not menus:
        return [], (f"{path}: no read `MENUS` list - the generated catalogue is "
                    f"not where this check reads it, so nothing could be "
                    f"matched")
    for menu in menus:
        if not isinstance(menu, dict):
            continue
        for key in ("title", "id"):
            value = menu.get(key)
            if isinstance(value, str):
                found.append(value)
        for value in menu.get("names") or ():
            if isinstance(value, str):
                found.append(value)
    if isinstance(groups, list):
        for group in groups:
            if isinstance(group, dict):
                for key in ("title", "id"):
                    value = group.get(key)
                    if isinstance(value, str):
                        found.append(value)
    if isinstance(aliases, dict):
        found.extend(k for k in aliases if isinstance(k, str))
    return found, ""


def names_from_desktop_js(directory: Path):
    """The labels the desktop's modules put on the things they build, and why
    nothing was read.

    Four label shapes, and nothing else. The alternative was measured and thrown
    away: every `export const SOME_NAME = "..."` in these files is 441 strings
    and most of them are sentences ("A Today card needs some words: what should
    it say?"), and every quoted string in every file is 14,287 - a set that
    begins to SWALLOW real drift ("Phone", "Privacy" and "Sensitive topics" all
    exist as somebody's message text), which is the one failure this check must
    not have. So what is kept is:

      * a `title:` field - a label or a tooltip the page shows;
      * a constant whose own name ends `_LABEL` or `_TITLE`;
      * the text of a button or heading the module builds itself, which is the
        third argument of `node(...)`/`el(...)` - this is where `Restore...`
        lives, and it is invisible to every other extractor here;
      * the app's own word tables, the objects bound to `WORDS`, `LABELS` or
        `TEXT` (`projects.js`'s `WORDS.shareable`, which draws the Shareable
        switch's heading).

    The last two were added after this check was pointed at the sixteen
    tutorials another pull request is adding: without them it reported three
    real labels (`Restore...`, `Shareable`, `Swipe to approve or deny`) as
    missing, which is exactly the false alarm a guard must not raise.
    """
    found: list[str] = []
    modules = sorted(p for p in directory.glob("*.js") if p.is_file())
    if not modules:
        return [], f"no .js module under {directory} - the desktop has no labels to read"
    for module in modules:
        try:
            text = module.read_text(encoding="utf-8", errors="replace")
        except OSError as err:
            return [], f"{module} could not be read ({err})"
        for match in re.finditer(r"(?<![\w])title:\s*\"([^\"]{1,60})\"", text):
            found.append(match.group(1))
        for match in re.finditer(
                r"^export const [A-Z][A-Z0-9_]*_(?:LABEL|TITLE) = \"([^\"]{1,60})\"",
                text, re.MULTILINE):
            found.append(match.group(1))
        for match in re.finditer(
                r"(?<![\w])(?:node|el)\(\s*\"[a-z0-9]+\"\s*,\s*\"[^\"]*\"\s*,"
                r"\s*\"([^\"]{1,60})\"", text):
            found.append(match.group(1))
        for table in re.finditer(
                r"^(?:export )?const (?:WORDS|LABELS|TEXT)\s*=\s*"
                r"(?:Object\.freeze\()?\{", text, re.MULTILINE):
            body = _balanced_text(text, text.index("{", table.start()))
            found.extend(re.findall(r":\s*\"([^\"]{1,60})\"", body))
    return found, ""


