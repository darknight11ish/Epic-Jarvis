#!/usr/bin/env python3
"""Every place a tutorial's `where` line sends the owner must be a name the two
apps really have.

    python3 tools/check_tutorial_places.py [-v] [--catalogue PATH]

WHY THIS EXISTS

The 23 tutorials are written as steps, and each step carries a `where` line
naming the button, card or screen the owner should use. Those lines are read on
the phone and on the PC, by someone who is new to the app, and they are the
most confident sentences in the whole project: "Settings -> Stop everything",
"Brain -> Voice -> Your voice print". A line that names a control the app does
not have is worse than a broken test, because it is user-facing, it is wrong,
and it survives every check the project already has - the tutorials are data,
not code, so nothing compiles them and nothing reads them.

That is not hypothetical. While the last sixteen tutorials were being written,
an agent invented three button labels in its first draft and caught them itself
("Choose the folder...", "Picture mode", "Choose the .zip..." are the real
ones), and two more tutorials described screens that do not exist at all (the
phone's "Timeline", and "tap to talk" on the phone). Nothing in this repository
could have seen either. This is the check that sees them.

WHAT IT READS

  * `backend/jarvis_tutorials.py` - the real file, not a fixture. Every `where`
    string in the `CATALOGUE` tuple and in the `FAQ` tuple, read from the
    module's own syntax tree so the line number reported is the line the owner
    would edit. The FAQ is read as well as the tutorials because it is the same
    `where` convention on the same screen ("Tutorials and the FAQ"), served by
    the same routes, and a wrong line there is the same confident mistake.
  * the names the DESKTOP really draws:
      - `jarvis-desktop/src/menu-catalog.js` - the generated catalogue both
        apps share. It is generated by `tools/gen_menu_cases.py` from
        `backend/jarvis_menus.py` and CI runs `--check`, so it cannot drift from
        the menu list the apps actually use. Every menu title, every id, every
        group title and every alias is a name this app knows a thing by.
      - every `*.html` under `jarvis-desktop/src/` - the visible words: the
        `<title>`, every `<h2>`, `<h3>` and `<summary>`, and the text of every
        `<button>`. This is where the real button labels live
        (`Choose a folder...`, `Choose the .zip...`) and where the real section
        headings live (`Picture mode`, `Hands-free ("Hey Jarvis")`).
      - every `*.js` under `jarvis-desktop/src/`, for four label shapes only: a
        `title:` field, a constant whose own name ends `_LABEL` or `_TITLE`
        (`SENSITIVE_LABEL`), the text `node(...)`/`el(...)` puts on a control it
        builds (`Restore...`), and the values in the app's own word tables
        (`WORDS`, `LABELS`, `TEXT` - `projects.js`'s `WORDS.shareable`). NOT
        every string in them: those alone are 14,287, and that set swallows
        real drift - see gap 4 below.
  * the names the PHONE really draws:
      - `jarvis-client/.../net/MenuCatalog.kt` - the phone's copy of the same
        generated catalogue.
      - `jarvis-client/.../ui/MenuPlaces.kt` - the `item(key = ...)` names the
        phone's screens really draw a menu under.
      - `jarvis-client/.../ui/Nav.kt` - the `Screen` enum: the phone's own
        names for its screens.
      - the `GroupHeading("...")` labels under `ui/screens/`, every
        `title = "..."` under `ui/`, and every constant in the phone's own code
        whose name ends `_TITLE`, `_LABEL` or `_NAME`
        (`SWIPE_TITLE = "Swipe to approve or deny"`).

A name found in EITHER app counts. Deciding which app a step is for is a
different question from whether the name exists, and it is the question this
check deliberately does not try to answer (see below).

`--catalogue PATH` reads a different file, on purpose, so the "can this check
fail?" question can be answered by pointing it at a copy. It prints a warning
saying so, and it is never used by CI: a run that read some other file must
never look like a run that read the real one.

WHAT IT CHECKS, AND WHAT IT DELIBERATELY DOES NOT

The shape it checks is the **breadcrumb**: a `where` line that contains `->`
and so presents a path to walk ("Brain -> Voice -> Hands-free"). Every piece of
that path that is name-shaped must be a name the apps have. A piece is NOT
name-shaped - and is skipped, not guessed at - when it is a sentence fragment:
it starts with an article or a filler word ("the switches", "a fact", "the
fact's own menu"), or it is a documentation reference (it holds a `/` or ends
`.md`), or it is longer than a name. A trailing qualifier is trimmed first, so
"Phone on the PC" is judged as `Phone` rather than as that whole phrase.

Two rules keep the matching honest rather than clever:

  * matching is EXACT, after case, whitespace, curly-quote and ellipsis
    normalising, plus one trailing `s` - no substring search, no fuzzy match,
    no "close enough". A substring search was tried and thrown away: it passed
    `a fact`, `the switches` and `Your voice print` against bodies of prose,
    which is exactly the crying-wolf failure this check must not have.
  * nothing is synthesised. Every accepted name is a string the app's own
    source really contains, so "this name exists" is a claim about the app and
    not about this script.

Five shapes are LEFT OUT on purpose, because they cannot be decided reliably
and a guard that cries wolf is worse than no guard:

  1. a `where` line with no `->`. It is a sentence ("The HUD window", "Any
     approval card", "The tray icon, or the Jarvis bar on the PC"), and pulling
     button names out of a sentence needs the kind of guessing that would fail
     an honest line. The proof this is a real gap: a wrong name written that
     way - "tap to talk, on the phone" - is not caught by this check.
  2. a name written in prose with no breadcrumb at all, quoted or not.
  3. whether a real name is in the RIGHT app, or on the RIGHT screen. "Brain ->
     Memory -> Forget a time frame" names two real things and one real card,
     and whether that card is under Memory or under History is a structural
     question the two apps answer differently (the phone's Brain is one long
     screen with group headings; the desktop's is a row of tabs).
  4. free-form string literals in the JS and Kotlin. Most of them are messages,
     not names, and accepting them all would pass almost anything - worse, it
     would SWALLOW real drift: measured, every quoted string in the two apps is
     14,287 names, and `Phone`, `Privacy` and `Sensitive topics` are all in it
     as somebody's message text. Only label-shaped strings are read (the four
     shapes above), which is a real gap: a name the app draws from a plain
     message string is invisible here.
  5. a label the app builds from its own word table under a NON-label name, or
     a `const val` in the phone's code that is not named `*_TITLE`, `*_LABEL` or
     `*_NAME`. Same reason as 4: widening to those was measured and swallowed
     `Phone` and `Privacy`.

The last two were found by pointing this check at the sixteen tutorials another
pull request is adding, which is also how the check was proved not to cry wolf:
with those shapes in, all 23 tutorials pass and every recorded entry still
matches, while an invented name anywhere in a breadcrumb still exits 1.

A recorded name still fails when it MOVES: the key is the kind of entry, its id,
its step number and the breadcrumb piece EXACTLY as the tutorial writes it, so a
name added to a different step, a step renumbered by an edit above it, the same
name in a second tutorial, or the same mistake reworded is a finding with no
entry and the check goes red again. An entry that stops being reported is itself
printed as stale - a recorded name is not a licence, and a list that can quietly
absorb a real finding is not a guard.

This check reads NO file from the owner's PC, makes no network call and writes
nothing. Every path in it is inside this checkout.
"""
