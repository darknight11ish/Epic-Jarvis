#!/usr/bin/env python3
"""Write Settings' "Abilities & commands" directory from the feature contract.

    python -B tools/gen_feature_directory.py [--check]

WHY THIS EXISTS

The owner's requirement (2026-10-22, Gemini Q2/Q8): Settings must include a
directory/search that indexes every feature, with exactly five plain labels, and
rows that are not switches must say so honestly, with an example phrase and a
screen path. Guessing those labels from catalogue prose would be a lie, so this
writer does not guess: it renders the CANONICAL cross-surface classification
that lock-hook's checker produces from both apps' evidence:

    contract/feature-controls.json        (schema 1, one row per feature)

That file is checked by `contract/check_feature_controls.py` (its owner's
checker), which runs the real `jarvis_quick.match()` on every example phrase and
checks every label against the five. THIS TOOL ONLY FORMATS IT, for the page.
A missing file, a changed schema, a row without a label or without its
`example_phrase`/`screen_path`, a declared count that disagrees with the rows,
or a label outside the five is a LOUD failure - never a defaulted row.

WHAT IT WRITES

* `jarvis-desktop/src/feature-directory.js` - the page's own copy
  (`FEATURE_DIRECTORY`, with `source_sha256` so a stale copy is detectable).
* `jarvis-desktop/tests/fixtures/feature-directory.json` - the same data for the
  suite, so a test can compare the page against the contract without a Python
  import.

The page never OFFERS a control from this file: every row is words. A switchable
row says which existing Settings card changes it; a Command-Only row says what
to ask and where; an Always-On row says it is a rule, not a setting. There is no
button, checkbox or select in the directory, by design - a directory is an index,
not a second settings surface.

`--check` exits 1 if either written file differs from what this tool would write
now, which is how a changed contract cannot silently leave the page stale.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
CONTRACT = REPO / "contract" / "feature-controls.json"
OUT_JS = REPO / "jarvis-desktop" / "src" / "feature-directory.js"
OUT_JSON = REPO / "jarvis-desktop" / "tests" / "fixtures" / "feature-directory.json"

#: The five labels the owner approved, in the order the page groups them. The
#: contract's `labels` map must contain EXACTLY these keys (its own checker
#: enforces the rest); this list stops a sixth label or a rename arriving here
#: unnoticed.
LABELS = (
    "Switchable / Adjustable (Typed & Settings)",
    "Settings-Only (By Design — Security Boundary)",
    "PC-Only Setting (Honest Refusal on Phone)",
    "Command-Only (Runs When You Ask — No Switch Needed)",
    "Always On (Core Safety Rule — Cannot Be Turned Off)",
)

#: The lead-approved plain note for a multi-field board whose Settings control
#: exists but whose typed path is still being wired (2026-10-22):
PLANNED_NOTE = "Settings control today; typed path still being wired."


def _resolves(phrase: str) -> bool:
    try:
        import sys
        sys.path.insert(0, str(REPO / "backend"))
        import jarvis_quick
        return jarvis_quick.match(phrase) is not None
    except Exception:
        return False


def fail(message: str) -> None:
    print(f"gen_feature_directory: {message}", file=sys.stderr)
    raise SystemExit(1)


def read_contract() -> dict:
    if not CONTRACT.exists():
        fail(f"{CONTRACT.relative_to(REPO)} is missing. The canonical feature "
             "classification is generated by the feature-controls checker; it "
             "must be in the tree before this directory can be written.")
    raw = CONTRACT.read_bytes()
    try:
        data = json.loads(raw.decode("utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        fail(f"{CONTRACT.relative_to(REPO)} is not readable JSON ({exc})")
    if data.get("schema") != 1:
        fail(f"unsupported contract schema {data.get('schema')!r} (expected 1)")
    labels = data.get("labels")
    if not isinstance(labels, dict) or list(labels) != list(LABELS):
        fail("the contract's five labels are not the owner-approved five, in "
             f"order: got {list(labels) if isinstance(labels, dict) else labels!r}")
    features = data.get("features")
    if not isinstance(features, list):
        fail("the contract has no features list")
    if data.get("feature_count") != len(features):
        fail(f"feature_count {data.get('feature_count')} does not match the "
             f"{len(features)} rows")
    ids = []
    for row in features:
        fid = row.get("id")
        if not isinstance(fid, str) or not fid:
            fail("a feature row has no id")
        ids.append(fid)
        if row.get("label") not in LABELS:
            fail(f"{fid}: label {row.get('label')!r} is not one of the five")
        evidence = row.get("label_evidence") or {}
        if not str(evidence.get("example_phrase") or "").strip():
            fail(f"{fid}: no example phrase - a directory row may not invent one")
        if not str(evidence.get("screen_path") or "").strip():
            fail(f"{fid}: no screen path - a directory row may not invent one")
    if len(set(ids)) != len(ids):
        fail("the contract lists a feature id twice")
    counts = {label: sum(1 for row in features if row.get("label") == label) for label in LABELS}
    # The mix itself is the owner's approved classification, pinned once in
    # `tools/check_feature_controls.py`; here the rows must only agree with the
    # contract's own declared `label_counts`, so a new feature row needs the
    # contract's data updated, never a literal in this writer.
    declared = data.get("label_counts")
    if not isinstance(declared, dict):
        fail("the contract has no label_counts")
    if counts != declared:
        fail("label counts do not match the contract's label_counts: "
             f"rows say {counts!r}, contract says {declared!r}")
    return {"raw": raw, "data": data}


_DESKTOP_PHONE = re.compile(
    r"^\s*desktop Settings:\s*(?P<desktop>.*?)\s*;\s*phone:\s*(?P<phone>.*?)\s*$",
    re.IGNORECASE | re.DOTALL)


def split_screen_path(where: str) -> tuple:
    """(desktop path, phone path) from either contract shape."""
    match = _DESKTOP_PHONE.match(where or "")
    if match:
        return match.group("desktop").strip(), match.group("phone").strip()
    parts = (where or "").split(" / ")
    desktop = parts[0].strip()
    phone = parts[-1].strip() if len(parts) > 1 else desktop
    return desktop, phone


def rows(data: dict) -> list:
    """The page's rows: one per feature, words only, honest notes where recorded."""
    planned = {row.get("id"): row for row in data.get("known_gaps") or []
               if row.get("status") == "planned"}
    multi = set()
    for board in data.get("multi_field") or []:
        for fid in board.get("features") or ():
            multi.add(fid)
    out = []
    for row in data.get("features") or []:
        fid = row["id"]
        evidence = row.get("label_evidence") or {}
        note = ""
        if fid in multi:
            note = PLANNED_NOTE
        elif fid in planned:
            gap = planned[fid]
            reason = str(gap.get("reason") or "").strip()
            owner = str(gap.get("owner") or "").strip()
            note = "Still being wired" + (f" (owner: {owner})" if owner else "")
            if reason:
                note += f": {reason}"
        where = str(evidence["screen_path"]).strip()
        # The contract writes the screen path for both apps. Two shapes are in
        # use: "desktop Settings: <path>; phone: <path>" (the regenerated
        # post-#734 contract) and "<path> / <path>" (the earlier one). Split
        # either so the page can say "On this PC" and "On the phone"; a path
        # with no separator is the same on both.
        where_desktop, where_phone = split_screen_path(where)
        # The DESKTOP screen ships in this same PR, so the contract's
        # " (planned)" marker for the desktop half is stale on the live page:
        # remove it from the desktop display only, and only as a trailing
        # marker. The phone half keeps the contract's planned wording until
        # Session B ships the phone directory. The raw contract text stays in
        # `where` and the canonical file is never modified here.
        if where_desktop.endswith(" (planned)"):
            where_desktop = where_desktop[:-len(" (planned)")].strip()
        if not note:
            note = str(row.get("label_note") or "").strip()
        out.append({
            "id": fid,
            "title": str(row.get("name") or fid),
            "group": str(row.get("group") or ""),
            "surface": str(row.get("surface") or ""),
            "label": row["label"],
            "status": str(row.get("status") or ""),
            "label_note": str(row.get("label_note") or "").strip(),
            "example": str(evidence["example_phrase"]).strip(),
            "example_ok": _resolves(str(evidence["example_phrase"]).strip()),
            "where": where,
            "where_desktop": where_desktop,
            "where_phone": where_phone,
            "note": note,
            # The directory NEVER draws a control; this flag is the page's own
            # reminder that a row is words, so a future edit cannot add a fake
            # switch by treating `status` as a toggle.
            "not_a_control": True,
        })
    return out


def render(data: dict, raw: bytes) -> tuple[str, str]:
    # Hash the canonical LF bytes. This checkout can hold the contract as CRLF
    # (autocrlf) while CI checks out the committed LF blob; hashing the local
    # bytes made source_sha256 platform-dependent and failed the frontend suite.
    sha = hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()
    payload = {
        "schema": 1,
        "source": "contract/feature-controls.json",
        "source_sha256": sha,
        "feature_count": len(data["features"]),
        "label_order": list(LABELS),
        "labels": {name: str(data["labels"][name]) for name in LABELS},
        "rows": rows(data),
    }
    body = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    js = (
        "// GENERATED by tools/gen_feature_directory.py - do not edit by hand.\n"
        "// Source: contract/feature-controls.json (the canonical, checked\n"
        f"// classification of all {len(data['features'])} features). Run `python -B\n"
        "// tools/gen_feature_directory.py` after that file changes, never retype\n"
        "// a label or an example here.\n"
        f"export const FEATURE_DIRECTORY = {body};\n"
        "\nexport default FEATURE_DIRECTORY;\n"
    )
    return js, body


def main(argv: list) -> int:
    check = "--check" in argv
    got = read_contract()
    js, fixture = render(got["data"], got["raw"])
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    if check:
        problems = []
        for path, want in ((OUT_JS, js), (OUT_JSON, fixture)):
            have = path.read_text(encoding="utf-8") if path.exists() else ""
            if have != want:
                problems.append(str(path.relative_to(REPO)))
        if problems:
            print("gen_feature_directory --check: stale or missing: "
                  + ", ".join(problems), file=sys.stderr)
            return 1
        print("feature-directory.js and its fixture match the feature contract "
              f"({got['data']['feature_count']} features, five labels)")
        return 0
    OUT_JS.write_text(js, encoding="utf-8", newline="\n")
    OUT_JSON.write_text(fixture, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_JS.relative_to(REPO)} and {OUT_JSON.relative_to(REPO)} "
          f"({got['data']['feature_count']} features, five labels)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
