#!/usr/bin/env python3
"""Generate the notes editor's ONE shared contract fixture, and check it.

    py -3 tools/gen_notes_cases.py            # write backend/notes-edit-cases.json
    py -3 tools/gen_notes_cases.py --check    # fail if it is stale; write nothing

WHY ONE FILE

The desktop and the phone each build a Notes surface against the same four
routes. `docs/JARVIS-API.md` section 170 is the prose contract; this fixture is
the same contract as data both app test suites can read, so the status codes
and answer bodies cannot drift between the two clients. It is generated from
`backend/jarvis_notes_edit.py` itself (its constants and its route names), so
it cannot say a limit the module does not use.

`count` in the list example is the number of rows in THAT answer, not the
vault's total - `truncated: true` says more exist. The unknown-save-id 404
carries `ok: false` and a plain `error` sentence so a client shows the PC's own
words instead of inventing one.

The app lanes own their own `jarvis-desktop/` and `jarvis-client/` copies; this
repository's single source of truth is `backend/notes-edit-cases.json` and the
file here regenerates it exactly.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "backend" / "jarvis_notes_edit.py"
OUT = ROOT / "backend" / "notes-edit-cases.json"

#: The example hash used in the fixture: sha256(b"hello note"), measured, so a
#: test that recomputes it agrees without a second literal.
EXAMPLE_TEXT = "hello note"
EXAMPLE_PATH = "Inbox/idea.md"


def _module():
    spec = importlib.util.spec_from_file_location("_gen_notes_cases_module", MODULE)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["_gen_notes_cases_module"] = mod
    spec.loader.exec_module(mod)
    return mod


def cases() -> dict:
    """The exact fixture body. Pure: no clock, no environment, no file read."""
    import hashlib
    mod = _module()
    example_sha = hashlib.sha256(EXAMPLE_TEXT.encode("utf-8")).hexdigest()
    new_text = "hello note, edited"
    new_sha = hashlib.sha256(new_text.encode("utf-8")).hexdigest()
    return {
        "_comment": (
            "Generated by tools/gen_notes_cases.py from backend/jarvis_notes_edit.py. "
            "Do not edit by hand. ONE shared copy for both apps: the desktop's and "
            "the phone's contract tests read this shape; re-run the generator after "
            "any contract change."
        ),
        "contract": "docs/JARVIS-API.md section 170",
        "action": mod.ACTION,
        "tier": "ask",
        "limits": {
            "max_file_bytes": mod.MAX_FILE_BYTES,
            "max_notes": mod.MAX_NOTES,
            "max_waiting": mod.MAX_WAITING,
            "max_query_chars": mod.MAX_QUERY_CHARS,
            "text_suffixes": list(mod.TEXT_SUFFIXES),
        },
        "routes": {
            "list": {
                "method": "GET",
                "path": mod.LIST_PATH,
                "query": {"q": "optional text; case-insensitive; bounded"},
                "answer": {
                    "status": 200,
                    "body": {
                        "ok": True,
                        "root": "<absolute vault path, for display only>",
                        "count": 1,
                        "notes": [{
                            "path": EXAMPLE_PATH,
                            "title": "idea",
                            "size": len(EXAMPLE_TEXT.encode("utf-8")),
                            "mtime": 1761900000.0,
                        }],
                        "truncated": False,
                    },
                    "note": "count is the rows in THIS answer, not the vault total; "
                            "truncated says more exist",
                },
                "errors": {
                    "503": {"ok": False, "error": "no Obsidian vault configured; the "
                                                 "sentence names the setting"},
                },
            },
            "read": {
                "method": "GET",
                "path": mod.READ_PATH,
                "query": {"path": "vault-relative .md/.txt path"},
                "answer": {
                    "status": 200,
                    "body": {
                        "ok": True,
                        "path": EXAMPLE_PATH,
                        "text": EXAMPLE_TEXT,
                        "sha256": example_sha,
                        "size": len(EXAMPLE_TEXT.encode("utf-8")),
                        "mtime": 1761900000.0,
                    },
                },
                "errors": {
                    "400": {"ok": False, "error": "bad, absolute, outside, hidden, "
                                                 "link or non-.md/.txt path"},
                    "404": {"ok": False, "error": "there is no note at that path"},
                    "413": {"ok": False, "error": "the note is over 2 MiB"},
                    "503": {"ok": False, "error": "no Obsidian vault configured"},
                },
            },
            "save": {
                "method": "POST",
                "path": mod.SAVE_PATH,
                "request": {"path": EXAMPLE_PATH, "text": new_text,
                            "expected_sha256": example_sha},
                "answers": {
                    "202": {
                        "state": "waiting",
                        "body": {"ok": True, "state": "waiting",
                                 "id": "<job id>", "path": EXAMPLE_PATH},
                        "note": "the approval card is up; the write happens only after Approve",
                    },
                    "200": {
                        "state": "saved",
                        "body": {"ok": True, "state": "saved",
                                 "path": EXAMPLE_PATH, "sha256": new_sha},
                        "note": "only when a future config makes the action tier auto",
                    },
                    "409": {
                        "state": "conflict",
                        "body": {"ok": False, "state": "conflict",
                                 "path": EXAMPLE_PATH,
                                 "current_sha256": "<hex of the current bytes>",
                                 "error": "the note changed since this edit started; "
                                          "nothing was written"},
                        "note": "nothing written, no card raised",
                    },
                    "400": {"ok": False, "state": "refused",
                            "error": "bad body or path; missing expected_sha256 or text"},
                    "413": {"ok": False, "state": "refused",
                            "error": "the new text is over 2 MiB"},
                    "429": {"ok": False, "state": "refused",
                            "error": "4 note saves are already waiting for approval - "
                                     "the sentence names the limit"},
                    "503": {"ok": False, "state": "refused",
                            "error": "no Obsidian vault configured"},
                },
            },
            "save_status": {
                "method": "GET",
                "path": mod.SAVE_PATH,
                "query": {"id": "the id from a 202"},
                "answer": {
                    "status": 200,
                    "states": ["waiting", "saved", "denied", "failed"],
                    "body": {"ok": True, "state": "saved",
                             "path": EXAMPLE_PATH, "sha256": new_sha,
                             "message": "Saved Inbox/idea.md into your Obsidian vault."},
                    "note": "ok is true only while waiting or after a save; "
                            "sha256 is null in every other state",
                },
                "errors": {
                    "404": {"ok": False, "state": "unknown",
                            "error": "There is no note save with that id on this PC."},
                },
            },
        },
    }


def render() -> str:
    return json.dumps(cases(), indent=2, sort_keys=False) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="fail if backend/notes-edit-cases.json is stale; write nothing")
    args = ap.parse_args(argv)
    want = render()
    if args.check:
        if not OUT.is_file():
            print(f"{OUT.relative_to(ROOT)} is missing; run: py -3 tools/gen_notes_cases.py")
            return 1
        if OUT.read_text(encoding="utf-8") != want:
            print(f"{OUT.relative_to(ROOT)} is stale; run: py -3 tools/gen_notes_cases.py")
            return 1
        print(f"the notes-editor contract fixture is up to date "
              f"({len(json.loads(want)['routes'])} routes, one shared copy)")
        return 0
    OUT.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} - {len(json.loads(want)['routes'])} routes, "
          "one shared copy for the desktop and the phone")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
