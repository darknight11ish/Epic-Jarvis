#!/usr/bin/env python3
"""Generate `backend/jarvis_recent_changes.py` from the record, and check it.

    py -3 tools/gen_recent_changes.py
    py -3 tools/gen_recent_changes.py --check

WHY THIS EXISTS

The owner asked (2026-11-07, the feature self-awareness audit): *"what changed
in your last update?"* The live backend answered it with a model, which said
"I haven't changed" or invented a list. The newest real changes are written in
this repository - `CHANGELOG.md` and the newest files under `changelog.d/` -
but the folder the owner actually RUNS has neither file, so the backend cannot
read them at runtime.

So the bullets are turned into a shipped Python module
(`backend/jarvis_recent_changes.py`), the same way
`tools/gen_feature_guide_catalogue.py` turns `features/features.json` into
`backend/jarvis_feature_catalogue.py`: a module can travel to the live folder,
a file that is not copied cannot. `--check` fails when the committed module is
stale, so the answer cannot drift from the record.

The VERSION is deliberately NOT baked in: the module reads `VERSION` beside
itself at answer time (as `jarvis_self_portrait` does), so a build number on
the owner's PC can never disagree with the text.

DETERMINISTIC BY CONSTRUCTION: no clock, no environment, no ordering that a
filesystem could vary - fragments are sorted by file name (they are
date-prefixed), the CHANGELOG is read in file order, duplicates are dropped and
each title is cut to a fixed length.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
CHANGELOG = REPO / "CHANGELOG.md"
FRAGMENTS = REPO / "changelog.d"
TARGET = REPO / "backend" / "jarvis_recent_changes.py"
TARGET_TWIN = REPO / "jarvis-backend" / "jarvis_recent_changes.py"

#: How many bullets the module carries. The answer shows two or three; a
#: couple more are kept so the fixed phrases have something to say without a
#: regeneration for every small bump.
KEEP = 5
#: One bullet's longest form, in characters. The answer must stay short enough
#: to read aloud in Live.
MAX_CHARS = 220

_BOLD_TITLE = re.compile(r"^-\s+\*\*(.+?)\*\*", re.MULTILINE)
_DATE_TAIL = re.compile(r"\s*\((?:19|20)\d\d(?:-\d\d){0,2}[^)]*\)\s*[.:]?\s*$")


def _clean(title: str) -> str:
    """Strip markdown and the record's trailing date; one readable line."""
    text = " ".join(str(title or "").split())
    text = _DATE_TAIL.sub("", text).strip()
    text = text.strip("*_` ").rstrip(".:; ")
    if len(text) > MAX_CHARS:
        cut = text[:MAX_CHARS].rsplit(" ", 1)[0]
        text = cut.rstrip(".:;,") + "..."
    return text


def _fragment_bullets() -> list:
    """Titles from the newest changelog.d fragments, newest file name first."""
    out = []
    if not FRAGMENTS.is_dir():
        return out
    for path in sorted(FRAGMENTS.glob("*.md"), key=lambda p: p.name, reverse=True):
        if path.name.lower() == "readme.md":
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        m = _BOLD_TITLE.search(text)
        if not m:
            continue
        title = _clean(m.group(1))
        if title:
            out.append(title)
        if len(out) >= KEEP:
            break
    return out


def _changelog_bullets() -> list:
    """The newest bullets the rolled changelog itself carries, in file order."""
    out = []
    try:
        text = CHANGELOG.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return out
    for m in _BOLD_TITLE.finditer(text):
        title = _clean(m.group(1))
        if title:
            out.append(title)
        if len(out) >= KEEP:
            break
    return out


def bullets() -> list:
    """The newest user-visible bullets, newest first, no duplicates."""
    seen, out = set(), []
    for title in _fragment_bullets() + _changelog_bullets():
        key = title.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append(title)
        if len(out) >= KEEP:
            break
    return out


def render(items: list) -> str:
    """The whole module's text, deterministic byte for byte."""
    lines = [
        '"""jarvis_recent_changes.py - "what changed in your last update?",',
        "answered from the project's own record.",
        "",
        "GENERATED by tools/gen_recent_changes.py from CHANGELOG.md and the newest",
        "changelog.d fragments. DO NOT HAND-EDIT. The live backend folder carries",
        "neither of those files, so the newest user-visible bullets travel as data,",
        "exactly like jarvis_feature_catalogue.py carries the feature list.",
        "",
        "The VERSION is NOT baked in: it is read beside this module at answer time,",
        "so a build number can never disagree with the text.",
        "",
        "Regenerate with:  py -3 tools/gen_recent_changes.py",
        ""/""  # noqa: D403 - the closing quote is written below, kept for a clean header
        if False else None  # pragma: no cover - placeholder never executed
    ]
    header = (
        '"""jarvis_recent_changes.py - "what changed in your last update?",\n'
        "answered from the project's own record.\n"
        "\n"
        "GENERATED by tools/gen_recent_changes.py from CHANGELOG.md and the newest\n"
        "changelog.d fragments. DO NOT HAND-EDIT. The live backend folder carries\n"
        "neither of those files, so the newest user-visible bullets travel as data,\n"
        "exactly like jarvis_feature_catalogue.py carries the feature list.\n"
        "\n"
        "The VERSION is NOT baked in: it is read beside this module at answer time,\n"
        "so a build number can never disagree with the text.\n"
        "\n"
        "Regenerate with:  py -3 tools/gen_recent_changes.py\n"
        "Check it is current:  py -3 tools/gen_recent_changes.py --check\n"
        '"""\n'
        "from __future__ import annotations\n"
        "\n"
        "from pathlib import Path\n"
        "\n"
    )
    body = ["#: The newest user-visible changes on record, newest first. Each is the\n",
            "#: record's own bold title, with its trailing date removed.\n",
            "BULLETS = (\n"]
    for item in items:
        body.append(f"    {item!r},\n")
    body.append(")\n")
    tail = (
        "\n\n"
        "#: One fixed sentence for a record that carries nothing - never an\n"
        "#: invented list and never the model's guess.\n"
        "NO_RECORD_WORDS = (\n"
        '    "The newest changes are not written down beside the program on this PC, "\n'
        '    "so I will not guess.")\n'
        "\n\n"
        "def version() -> str:\n"
        '    """The VERSION beside this module, or "" when this PC has none."""\n'
        "    try:\n"
        '        text = (Path(__file__).resolve().parent / "VERSION").read_text(\n'
        '            encoding="utf-8", errors="replace").strip()\n'
        "    except OSError:\n"
        '        return ""\n'
        "    return text if text else \"\"\n"
        "\n\n"
        "def bullets(limit: int = 3) -> list:\n"
        '    """The newest bullets, at most `limit`, never a guess."""\n'
        "    try:\n"
        "        n = int(limit)\n"
        "    except (TypeError, ValueError):\n"
        "        n = 3\n"
        "    return [b for b in BULLETS if b][: max(0, n)]\n"
        "\n\n"
        "def answer(limit: int = 3) -> str:\n"
        '    """What changed in the last update: the version, then the real bullets."""\n'
        "    got = version()\n"
        "    lead = (f\"This PC runs Jarvis {got}.\" if got\n"
        '            else "The version is not written down beside the program on this PC.")\n'
        "    items = bullets(limit)\n"
        "    if not items:\n"
        "        return lead + \" \" + NO_RECORD_WORDS\n"
        "    listed = \"; \".join(item.rstrip(\".;\") for item in items)\n"
        "    return lead + \" The newest changes on record are: \" + listed + \".\"\n"
    )
    return header + "".join(body) + tail


def current_text() -> str:
    try:
        return TARGET.read_text(encoding="utf-8")
    except OSError:
        return ""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="fail when the committed module is stale; write nothing")
    ap.add_argument("--print", dest="show", action="store_true",
                    help="print the bullets found, one per line")
    args = ap.parse_args(argv)
    found = bullets()
    if args.show:
        for item in found:
            print(item)
        return 0
    text = render(found)
    if args.check:
        have = current_text()
        if have != text:
            print("OUT OF DATE: backend/jarvis_recent_changes.py - "
                  "run python3 tools/gen_recent_changes.py", file=sys.stderr)
            return 1
        print(f"ok - backend/jarvis_recent_changes.py carries {len(found)} newest bullets")
        return 0
    TARGET.write_bytes(text.encode("utf-8"))
    if TARGET_TWIN.parent.exists():
        TARGET_TWIN.write_bytes(text.encode("utf-8"))
    print(f"wrote {TARGET.relative_to(REPO)} with {len(found)} newest bullets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
