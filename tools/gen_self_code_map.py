class CoverageError(RuntimeError):
    """The tree holds a file no subsystem owns, or one two of them claim."""


def _run(root: Path, *args: str) -> str:
    """git's stdout, decoded, with a plain error when git cannot answer."""
    try:
        done = subprocess.run(["git", "-C", str(root), *args], capture_output=True,
                              check=False)
    except OSError as exc:
        raise RuntimeError(f"git could not be run in {root.name}: {exc}") from exc
    if done.returncode != 0:
        why = done.stderr.decode("utf-8", "replace").strip().splitlines()
        raise RuntimeError("git " + " ".join(args) + " failed: "
                           + (why[0] if why else f"exit {done.returncode}"))
    return done.stdout.decode("utf-8", "replace")


def provenance(root: Path = REPO) -> dict:
    """The commit the map is built from, and that commit's own date.

    `built_at` is the COMMIT date, never "now": two runs on one commit must
    produce identical bytes, and a wall-clock timestamp makes that impossible.
    """
    ref = _run(root, "rev-parse", "HEAD").strip()
    built_at = _run(root, "show", "-s", "--format=%cI", "HEAD").strip()
    return {"ref": ref, "built_at": built_at}


def recent_commits(ref: str, root: Path = REPO) -> list:
    """The newest subjects and dates at `ref`, so the map can say what changed."""
    raw = _run(root, "log", f"-{RECENT_MAX}", "--format=%H%x09%cI%x09%s", ref)
    out = []
    for line in raw.splitlines():
        parts = line.split("\t", 2)
        if len(parts) != 3:
            continue
        sha, when, subject = parts
        out.append({"sha": sha, "date": when[:10], "subject": subject.strip()})
    return out


def tree_files(root: Path = REPO) -> list:
    """Every path a commit would carry, sorted: the index.

    `git ls-files --cached` is the index - the files git already knows, at the
    paths they will be committed under. A file that is brand new has to be
    staged (`git add`, or `git add -N` to record only the path) before it is
    part of the tree this map describes, which is the same rule a commit
    follows. Untracked scratch - a suite's temporary database, an agent's note -
    is deliberately NOT walked: it is not part of the repository, and a map that
    changed because a test left a file behind would fail for the wrong reason.
    """
    raw = _run(root, "ls-files", "-z", "--cached")
    return sorted({p.replace("\\", "/") for p in raw.split("\0") if p})


def excluded_reason(path: str) -> str:
    """Why `path` is outside the map, or "" when it belongs to a subsystem."""
    for pattern, why in EXCLUDED:
        if fnmatch.fnmatchcase(path, pattern):
            return why
    return ""


def _first_sentence(text: str, limit: int = SUMMARY_MAX) -> str:
    """A docstring's first sentence, flattened and bounded.

    A map line has to be readable in a chat answer, so it keeps ONE sentence and
    stops at `limit` characters - cut at a word boundary and marked with an
    ellipsis rather than in the middle of a word.
    """
    flat = " ".join(str(text or "").split())
    if not flat:
        return ""
    cut = len(flat)
    for i, ch in enumerate(flat):
        if ch in ".!?" and (i + 1 == len(flat) or flat[i + 1] == " "):
            cut = i + 1
            break
    sentence = flat[:cut].strip()
    if len(sentence) > limit:
        sentence = sentence[:limit].rsplit(" ", 1)[0].rstrip(" ,;:-") + "..."
    return sentence


def module_summary(root: Path, rel: str) -> str:
    """The first sentence of a module's own docstring, or "" if it has none.

    Parsed from the source with `ast`, never imported: a map must not run the
    code it is describing. A file that will not parse gets no summary rather
    than stopping the map - the repository already has a suite for syntax.
    """
    try:
        source = (root / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    try:
        doc = ast.get_docstring(ast.parse(source)) or ""
    except (SyntaxError, ValueError):
        return ""
    return _first_sentence(doc)


def _module_path(name: str) -> str:
    return "backend/" + name + ".py"


def _rows() -> list:
    """The subsystem table as (id, title, purpose, areas, patterns, keys, tests,
    docs) -- resolved once, so every helper agrees about the same table."""
    rows = []
    for row in SUBSYSTEMS:
        patterns = [_module_path(n) for n in row["modules"]]
        patterns.extend(row["paths"])
        keys = []
        for name in row["key_modules"]:
            if "/" in name:
                keys.append(name)
            elif name.endswith(".py"):
                keys.append(_module_path(name[:-3]))
            elif name.endswith((".json", ".md", ".toml")):
                keys.append(name)
            else:
                keys.append(_module_path(name))
        rows.append({
            "id": row["id"],
            "title": row["title"],
            "group": row["group"],
            "purpose": row["purpose"],
            "areas": list(row["areas"]),
            "patterns": patterns,
            "key_modules": keys,
            "tests": list(row["tests"]),
            "docs": list(row["docs"]),
        })
    return rows


def _claims(path: str, rows: list) -> list:
    """The subsystem ids whose patterns match `path`."""
    return [r["id"] for r in rows
            if any(fnmatch.fnmatchcase(path, p) for p in r["patterns"])]


def assign(files: list) -> tuple:
    """(subsystem id -> files, excluded pattern -> files), or CoverageError.

    Every non-excluded path must belong to exactly one subsystem. Both halves
    are errors and both are named in the message with the paths, because "some
    file is not covered" is useless without the file names.
    """
    rows = _rows()
    by_id = {r["id"]: [] for r in rows}
    dropped = {}
    unowned, shared = [], []
    for path in files:
        why = excluded_reason(path)
        if why:
            dropped.setdefault(why, []).append(path)
            continue
        owners = _claims(path, rows)
        if not owners:
            unowned.append(path)
        elif len(owners) > 1:
            shared.append((path, owners))
        else:
            by_id[owners[0]].append(path)
    problems = []
    if unowned:
        problems.append(
            f"{len(unowned)} file(s) belong to no subsystem, so the map would "
            f"silently forget them:\n  " + "\n  ".join(unowned[:60])
            + ("\n  ...and more" if len(unowned) > 60 else ""))
    if shared:
        listed = [f"{p}  ({', '.join(o)})" for p, o in shared[:60]]
        problems.append(
            f"{len(shared)} file(s) belong to more than one subsystem, so the map "
            f"would count them twice:\n  " + "\n  ".join(listed)
            + ("\n  ...and more" if len(shared) > 60 else ""))
    if problems:
        raise CoverageError("the tree does not divide into the subsystem table:\n\n"
                            + "\n\n".join(problems))
    return by_id, dropped


def _areas_for(files: list) -> list:
    """The areas a subsystem spans, from the files it owns."""
    areas = set()
    for path in files:
        head = path.split("/", 1)[0]
        if "/" not in path:
            # A root file: the documents at the top of the repository, or code
            # that sits at the top (sitecustomize.py is deploy's).
            areas.add("docs" if path.endswith((".md", ".txt")) or path == "LICENSE"
                      else "backend")
        elif head in _AREA_OF_DIR:
            areas.add(_AREA_OF_DIR[head])
        elif head == "features":
            areas.add("backend")
        elif head in ("videos",):
            areas.add("docs")
        else:
            areas.add("backend")
    return sorted(areas)


def _top_level(files: list) -> list:
    """The major directories and root files, with one plain line each."""
    counts = {}
    for path in files:
        head = path.split("/", 1)[0]
        if "/" in path:
            counts[head] = counts.get(head, 0) + 1
    out = []
    for name in sorted(counts, key=lambda n: (-counts[n], n)):
        if name not in _MAJOR_DIRS:
            continue
        line = TOP_LEVEL.get(name) or f"{counts[name]} tracked files"
        out.append({"path": name + "/", "line": line,
                    "files": counts[name]})
    for name in _ROOT_FILES:
        if name in files:
            out.append({"path": name,
                        "line": "the one version number this repository releases "
                                "under, read by the apps and the deploy",
                        "files": 1})
    return out


def build_map(root: Path, files: list, *, ref: str, built_at: str,
              commits: list) -> dict:
    """The whole map document, from a tree and four facts about its commit.

    Pure apart from reading files under `root` (VERSION and each key module's
    docstring). `files` is the tracked-file list, so a caller can hand it a
    synthetic tree - which is exactly how the coverage failure is tested.
    """
    by_id, dropped = assign(files)
    rows = _rows()
    version = ""
    try:
        version = (root / "VERSION").read_text(encoding="utf-8").strip()
    except OSError:
        version = ""
    subsystems = []
    missing = []
    for row in rows:
        owned = sorted(by_id[row["id"]])
        keys = []
        for path in row["key_modules"]:
            if not (root / path).is_file():
                missing.append(f"{row['id']}: key module {path}")
            keys.append({"path": path,
                         "summary": module_summary(root, path)})
        tests = [t for t in row["tests"] if (root / t).is_file()]
        docs = [d for d in row["docs"] if (root / d).is_file()]
        for path in row["tests"] + row["docs"]:
            if not (root / path).is_file():
                missing.append(f"{row['id']}: reference {path}")
        subsystems.append({
            "id": row["id"],
            "title": row["title"],
            "group": row["group"],
            "purpose": row["purpose"],
            "files": owned,
            "file_count": len(owned),
            "key_modules": keys,
            "tests": tests,
            "docs": docs,
            "areas": _areas_for(owned) or row["areas"],
        })
    if missing:
        # A reference the tree no longer holds is a stale map, and dropping it
        # would hide the drift this generator exists to catch.
        raise CoverageError(
            "the map names files this tree does not have, so it would describe a "
            "tree that no longer exists:\n  " + "\n  ".join(missing))
    excluded = [{"why": why, "count": len(paths), "examples": sorted(paths)[:3]}
                for why, paths in sorted(dropped.items(),
                                         key=lambda kv: (-len(kv[1]), kv[0]))]
    covered = sum(s["file_count"] for s in subsystems)
    return {
        "schema": SCHEMA,
        "repo": OWNER_REPO,
        "public": True,
        "ref": ref,
        "built_at": built_at,
        "version": version,
        "generated_by": "tools/gen_self_code_map.py",
        "about": ("A map of Jarvis's own code as it stood at this commit: the major "
                  "parts, the files each part owns, the module to start reading for "
                  "each, and the suites and documents that go with it. It names code; "
                  "it does not hold code and it runs nothing."),
        "architecture": [dict(a) for a in ARCHITECTURE],
        "subsystems": subsystems,
        "recent_commits": commits[:RECENT_MAX],
        "top_level": _top_level(files),
        "coverage": {
            "tracked_files": len(files),
            "covered": covered,
            "excluded": len(files) - covered,
            "subsystems": len(subsystems),
        },
        "excluded_patterns": excluded,
    }


def render(doc: dict) -> str:
    """The map as the bytes that are committed: sorted keys where order is not a
    decision, one value per line so the first differing line names the change."""
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def generate(root: Path = REPO) -> str:
    """Build the map from this checkout, as text."""
    info = provenance(root)
    return render(build_map(root, tree_files(root),
                            ref=info["ref"], built_at=info["built_at"],
                            commits=recent_commits(info["ref"], root)))


def _load(path: Path):
    """The committed map as a dict, or (None, plain sentence)."""
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None, (f"{path.name} is not there, so there is nothing to check: "
                      f"run this generator with no --check first.")
    except OSError as exc:
        return None, f"{path.name} could not be read ({type(exc).__name__})."
    try:
        return json.loads(text), ""
    except ValueError as exc:
        return None, f"{path.name} is not valid JSON ({exc})."


def _dirty_refusal(root: Path, map_path: Path) -> str:
    """Why `--check` should refuse this tree, or "".

    `--check` answers "does the committed map still describe this tree?". Run
    on a tree nobody committed, that answer is about code the repository does
    not have - so it refuses when the tree is dirty AND the map itself is clean
    (the map is committed, the code around it has moved). When the map is one of
    the changes, the person is building or updating it and a dirty tree is the
    point; comparing is exactly what they asked for.
    """
    status = _run(root, "status", "--porcelain")
    if not status.strip():
        return ""
    try:
        rel = map_path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return ""
    for line in status.splitlines():
        changed = line[3:].strip().strip('"').replace("\\", "/")
        if changed == rel or changed.endswith("/" + rel):
            return ""
    return ("the working tree has uncommitted changes and the map itself is not "
            "one of them, so checking it would say the map matches a tree nobody "
            "committed. Commit or stash first, or run without --check to write the "
            "map this tree produces.")


def check(root: Path = REPO, map_path: Path = None) -> int:
    """0 when the committed map is what this tree produces, 1 when it is not."""
    map_path = Path(map_path or (root / MAP_REL))
    try:
        return _check(root, map_path)
    except RuntimeError as exc:
        # A git failure is a plain sentence, never a traceback from a tool.
        print(f"the map could not be checked: {exc}")
        return 1


def _check(root: Path, map_path: Path) -> int:
    planted = _load(map_path)
    if planted[0] is None:
        print(planted[1])
        return 1
    committed = planted[0]
    why = _dirty_refusal(root, map_path)
    if why:
        print(why)
        return 1
    info = provenance(root)
    try:
        fresh = render(build_map(
            root, tree_files(root),
            ref=str(committed.get("ref") or info["ref"]),
            built_at=str(committed.get("built_at") or info["built_at"]),
            commits=list(committed.get("recent_commits") or []),
        ))
    except CoverageError as exc:
        print(str(exc))
        return 1
    want = map_path.read_text(encoding="utf-8")
    if fresh == want:
        print(f"{map_path.name} matches this tree: "
              f"{len(json.loads(want)['subsystems'])} subsystems, "
              f"{json.loads(want)['coverage']['covered']} files covered.")
        return 0
    old_lines, new_lines = want.splitlines(), fresh.splitlines()
    for i in range(max(len(old_lines), len(new_lines))):
        old = old_lines[i] if i < len(old_lines) else "<the committed map ends here>"
        new = new_lines[i] if i < len(new_lines) else "<the tree produces more lines>"
        if old != new:
            print(f"{map_path.name} has drifted from this tree - first difference "
                  f"at line {i + 1}:")
            print(f"  committed: {old.strip()[:200]}")
            print(f"  this tree: {new.strip()[:200]}")
            break
    print("Run `py -3 tools/gen_self_code_map.py` and commit the result.")
    return 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Build or check backend/jarvis-self-code.json.")
    parser.add_argument("--check", action="store_true",
                        help="compare the committed map with this tree; exit 1 on drift")
    parser.add_argument("--map-out", default=None,
                        help="write the map here instead of backend/jarvis-self-code.json")
    args = parser.parse_args(argv)
    out = Path(args.map_out) if args.map_out else (REPO / MAP_REL)
    if not out.is_absolute():
        out = REPO / out
    if args.check:
        rc = check(REPO, out)
        if rc == 0 and not args.map_out:
            # Ruling Q4 (2026-11-08): a map that matches the tree but whose
            # published base twin differs is the same failure in a new shape, so
            # --check refuses it too instead of leaving it for the audit job.
            twin = REPO / TWIN_REL
            if not twin.exists() or twin.read_bytes() != out.read_bytes():
                print(f"the map and {TWIN_REL} differ - run "
                      "`py -3 tools/gen_self_code_map.py` to write both in one run.")
                return 1
        return rc
    try:
        text = generate(REPO)
    except CoverageError as exc:
        print(str(exc))
        return 1
    except RuntimeError as exc:
        print(f"the map could not be built: {exc}")
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(text.encode("utf-8"))
    twin = None
    if not args.map_out:
        # The base's copy, in the SAME run as the repository copy (ruling Q4,
        # 2026-11-08): one command, both files, always the same bytes.
        twin = REPO / TWIN_REL
        twin.parent.mkdir(parents=True, exist_ok=True)
        twin.write_bytes(text.encode("utf-8"))
    doc = json.loads(text)
    cov = doc["coverage"]
    print(f"wrote {out.name}: {cov['subsystems']} subsystems, "
          f"{cov['covered']} files covered, {cov['excluded']} excluded by name, "
          f"{cov['tracked_files']} tracked in total.")
    if twin is not None:
        print(f"also wrote {TWIN_REL} (the published base twin, the same bytes).")
    for row in doc["excluded_patterns"]:
        print(f"  excluded {row['count']:>4}  {row['why']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
