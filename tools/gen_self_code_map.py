#!/usr/bin/env python3
"""Build `backend/jarvis-self-code.json`: a map of Jarvis's own code.

    py -3 tools/gen_self_code_map.py
    py -3 tools/gen_self_code_map.py --check
    py -3 tools/gen_self_code_map.py --map-out somewhere/else.json

WHY THIS EXISTS. Asked "what is your own GitHub repository?", the live backend
answered "I don't have a public GitHub repository of my own" - it had no idea
that the code it runs IS this repository. `jarvis_repomap.py` can map a folder
the owner names; `jarvis_self_portrait.py` knows its version and its tools;
`jarvis_feature_catalogue.py` knows what features DO. None of them knows which
module implements which part of Jarvis. This generator writes that down, so a
shipped reader (`backend/jarvis_self_code.py`) can answer from it with no model
and no code execution.

THE MAP IS GENERATED, NEVER TYPED. The file it writes is a product of the tree
it is run in: the paths, each key module's own docstring summary, the repo's
VERSION, the commit it was built from and that commit's date, and its newest
twenty commit subjects. `--check` re-derives all of it in memory and compares,
byte for byte, with the committed file - so a module that moved, a docstring
that changed or a subsystem whose files drifted fails loudly instead of leaving
a map that quietly describes last week.

COMPLETENESS IS THE POINT, SO IT IS CHECKED. Every file git would track is
assigned to exactly ONE subsystem by the table below. The generator exits
non-zero, naming every path, when a file belongs to none or to two - so "every
major part of its own code" is a property a machine proves rather than a claim
in a docstring. Generated, binary and vendored files are skipped by an explicit
named list (`EXCLUDED`), and the counts are printed and stored in the map so
nothing is dropped silently. The map file itself is skipped: it is the output.

WHAT IT DELIBERATELY DOES NOT DO: it does not read whole code bodies into the
map (only a module's first docstring sentence), it does not run anything it
maps, it opens no socket, it writes nothing but the map and its published base
twin (the same bytes, in the same run - ruling Q4, 2026-11-08), and it has no
absolute path anywhere in its output. It walks the INDEX - the files a commit would carry
- so a brand-new file has to be staged (`git add`, or `git add -N` to record
only its path) before it is part of the tree the map describes, exactly as a
commit requires. Untracked scratch (a suite's temporary database, an agent's
note) is not walked, because it is not part of the repository. `--check`
therefore refuses when the tree is dirty AND the committed map is clean: then
"the map still matches" would be an answer about a tree nobody committed (see
`_dirty_refusal`).

Standard library only. Runs anywhere git does.
"""
