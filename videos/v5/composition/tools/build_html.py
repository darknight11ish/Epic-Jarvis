# ---------------------------------------------------------------- stations
# Each station is laid out in its own frame of the strip; `pos` is where it
# sits (left for landscape, top for upright), filled in per cut.

def col(part, hour, say=None, reply=None, sid="", later=False):
    s = f'''            <div class="col">
              <div class="part">{part}</div>
              <div class="hour">{hour}</div>
'''
    if say:
        s += f'''              <div class="who" id="{sid}-you">You</div>
              <div class="say" id="{sid}-say">{say}</div>
'''
    if later:
        s += f'''              <div class="who later" id="later">A minute later</div>
'''
    if reply:
        s += f'''              <div class="who" id="{sid}-jw">Jarvis</div>
              <div class="reply" id="{sid}-reply">{reply}</div>
'''
    return s + "            </div>\n"


def claim(sid, html):
    return f'            <div class="claim" id="{sid}-claim">{html}</div>\n'


def shot(sid, imgs, extra="", where=""):
    s = f'            <div class="shot" id="{sid}-shot">\n'
    if where:
        s += f'              <div class="where">{where}</div>\n'
    for i, src in imgs:
        s += f'              <img id="{i}" src="assets/ui/{src}" alt="" />\n'
    return s + extra + "            </div>\n"


def station(sid, pos, axis, body, night=False):
    side = "top" if axis == "y" else "left"
    return (f'          <section class="station{" night" if night else ""}" id="st-{sid}" style="{side}: {pos}px">\n'
            + body + "          </section>\n")


