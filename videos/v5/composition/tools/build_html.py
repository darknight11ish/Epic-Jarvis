def build(kind):
    t = TIMING["timing" if kind == "landscape" else "timing-vertical"]
    H = t["hits"]
    if kind == "landscape":
        w, h, cid, axis = 1920, 1080, "jarvis-v5", "x"
        body = stations_landscape()
        heroes = [[0, "idle"],
                  [H["briefSay"], "listening"], [H["briefCard"], "speaking"], [H["briefClaim"] + 1.0, "idle"],
                  [H["focusSay"], "listening"], [H["focusCard"], "idle"], [H["drift"], "speaking"], [H["drift"] + 1.0, "idle"],
                  [H["tellSay"], "listening"], [H["tellCard"], "approval"], [H["approve"] + 0.2, "idle"],
                  [H["learnSay"], "listening"], [H["saved"], "idle"],
                  [H["asleep"], "standby"]]
        sun = {"dx": 0, "dy": 280, "s": 1.9}
        extra = ""
    else:
        w, h, cid, axis = 1080, 1920, "jarvis-v5-vertical", "y"
        body = stations_vertical()
        heroes = [[0, "idle"],
                  [H["focusSay"], "listening"], [H["focusCard"], "idle"], [H["drift"], "speaking"], [H["drift"] + 1.0, "idle"],
                  [H["tellSay"], "listening"], [H["tellCard"], "approval"], [H["approve"] + 0.2, "idle"],
                  [H["end"] - 0.3, "idle"]]
        sun = {"dx": 400, "dy": -120, "s": 1.9}
        extra = '    <link rel="stylesheet" href="assets/vertical.css" />\n'
    boxes = {k: (ROOT / "assets" / "ui" / f).read_text().strip() for k, f in
             (("__APPROVE__", "tellme-card-approve.json"), ("__ERASE__", "memory-saved-erase.json"))}
    script = SCENES
    for k, v in boxes.items():
        script = script.replace(k, v)
    script = (script.replace("__CID__", cid).replace("__AXIS__", axis)
              .replace("__HERO__", json.dumps(heroes)).replace("__SUN__", json.dumps(sun)))
    html = HEAD.format(w=w, h=h, title="Jarvis: a day with Jarvis" + ("" if kind == "landscape" else " (upright)"),
                       timing="timing" if kind == "landscape" else "timing-vertical",
                       audio="audio-data" if kind == "landscape" else "audio-data-vertical",
                       extra=extra, cls=kind, cid=cid, dur=t["dur"])
    html += body + TAIL.format(script=script, dur=t["dur"], score="score" if kind == "landscape" else "score-vertical")
    (ROOT / ("index.html" if kind == "landscape" else "vertical.html")).write_text(html)


if __name__ == "__main__":
    build("landscape")
    build("vertical")
    print("wrote index.html and vertical.html")
